import { studiodEndpoint } from '../../../runtime/studiod-endpoint'
import { normalizeCanvasInputs } from './canvas-inputs'
import { formatParamsError } from './param-errors'
import { randomUUID } from 'node:crypto'
import { toolNameOf, describeCapability, listCapabilities, METHODS, type MethodName } from '@vis/protocol'
import { connect, RpcCallError, type RpcClient } from './client'

// stdio MCP server: tools come from the capability table for Codex, DeepSeek Harness, and other agents (0005 "Capability entry point: MCP")
const SUPPORTED_VERSIONS = ['2025-11-25', '2025-06-18', '2025-03-26', '2024-11-05']
const SERVER_INFO = { name: 'vis', version: '0.0.0' }

type JsonRpcMessage = { jsonrpc?: string; id?: string | number | null; method?: string; params?: unknown }
type Tool = { name: string; description: string; inputSchema: Record<string, unknown> }

export type McpServer = {
  /** Handles one client message; returns undefined for notifications */
  handle(message: JsonRpcMessage): Promise<object | undefined>
  close(): void
}

export { toolNameOf } from '@vis/protocol'

function buildTools(): Map<string, { method: MethodName; tool: Tool }> {
  const tools = new Map<string, { method: MethodName; tool: Tool }>()
  for (const entry of listCapabilities('agent')) {
    const method = entry.method as MethodName
    // The capability catalog is tools/list itself; do not expose it twice
    if (method.startsWith('capabilities.')) continue
    const described = describeCapability(method, 'agent')!
    const schema = { ...(described.params as Record<string, unknown>) }
    delete schema.$schema
    if (method === 'canvas.apply') {
      const ops = (schema.properties as Record<string, { items: { oneOf: { properties: Record<string, unknown>; required: string[] }[] } }>).ops!
      for (const op of ops.items.oneOf) {
        if (op.properties.inputNodeIds && !op.required.includes('inputNodeIds')) op.properties.inputs = op.properties.inputNodeIds
      }
    }
    // requestId is optional and generated by the server; retries must reuse the requestId returned initially
    if (Array.isArray(schema.required)) schema.required = schema.required.filter(k => k !== 'requestId')
    const name = toolNameOf(method)
    tools.set(name, { method, tool: { name, description: described.description, inputSchema: schema } })
  }
  return tools
}

export function createMcpServer(env: Record<string, string | undefined>): McpServer {
  const socketPath = env.VIS_SOCKET ?? (env.VIS_DATA_DIR ? studiodEndpoint(env.VIS_DATA_DIR) : undefined)
  const tools = buildTools()
  let client: Promise<RpcClient> | undefined

  function studiod(): Promise<RpcClient> {
    if (!socketPath || !env.VIS_AGENT_TOKEN) return Promise.reject(new RpcCallError('invalid_params', 'VIS_SOCKET and VIS_AGENT_TOKEN must be set'))
    client ??= connect({ socketPath, credential: { kind: 'agent', token: env.VIS_AGENT_TOKEN } })
    // Reconnect on the next call after a connection failure or disconnect
    client.catch(() => { client = undefined })
    return client
  }

  async function callTool(name: string, args: unknown) {
    const entry = tools.get(name)
    if (!entry) return toolError('invalid_params', `Unknown tool ${name}`)
    let params: Record<string, unknown> = { ...(args && typeof args === 'object' ? args : {}) }
    const schema = entry.tool.inputSchema as { properties?: Record<string, unknown> }
    if (schema.properties && Object.hasOwn(schema.properties, 'requestId') && params.requestId === undefined) params.requestId = randomUUID()
    if (entry.method === 'canvas.apply') {
      try { params = normalizeCanvasInputs(params) } catch (error) { return toolError('invalid_params', (error as Error).message, params.requestId) }
    }
    const checked = METHODS[entry.method].params.safeParse(params)
    if (!checked.success) return toolError('invalid_params', formatParamsError(entry.method, checked.error, params), params.requestId)
    try {
      const rpc = await studiod()
      const result = await rpc.call(entry.method, checked.data)
      const output = params.requestId === undefined ? result : { ...(result as object), requestId: params.requestId }
      return { content: [{ type: 'text', text: JSON.stringify(output) }] }
    } catch (error) {
      if (error instanceof RpcCallError) {
        if (error.code === 'unavailable') client = undefined
        return toolError(error.code, error.message, params.requestId, error.conflicts, error.data)
      }
      return toolError('unavailable', error instanceof Error ? error.message : String(error), params.requestId)
    }
  }

  async function dispatch(method: string, params: unknown): Promise<unknown> {
    switch (method) {
      case 'initialize': {
        const requested = (params as { protocolVersion?: unknown } | undefined)?.protocolVersion
        const protocolVersion = typeof requested === 'string' && SUPPORTED_VERSIONS.includes(requested) ? requested : SUPPORTED_VERSIONS[1]
        return { protocolVersion, capabilities: { tools: { listChanged: false } }, serverInfo: SERVER_INFO }
      }
      case 'ping': return {}
      case 'tools/list': {
        if (!socketPath || !env.VIS_AGENT_TOKEN) return { tools: [...tools.values()].map(t => t.tool) }
        // Generate from the caller capabilities returned by the gateway; the client does not infer permissions.
        const rpc = await studiod()
        const { capabilities } = METHODS['capabilities.list'].result.parse(await rpc.call('capabilities.list', {}))
        const allowed = new Set(capabilities.map(capability => capability.method))
        return { tools: [...tools.values()].filter(entry => allowed.has(entry.method)).map(entry => entry.tool) }
      }
      case 'tools/call': {
        const p = params as { name?: unknown; arguments?: unknown } | undefined
        return callTool(typeof p?.name === 'string' ? p.name : '', p?.arguments)
      }
      default: throw Object.assign(new Error(`Unknown method ${method}`), { rpcCode: -32601 })
    }
  }

  return {
    async handle(message) {
      if (typeof message.method !== 'string') return undefined
      const id = message.id
      if (id === undefined || id === null) return undefined
      try {
        return { jsonrpc: '2.0', id, result: await dispatch(message.method, message.params) }
      } catch (error) {
        return { jsonrpc: '2.0', id, error: { code: (error as { rpcCode?: number }).rpcCode ?? -32603, message: (error as Error).message } }
      }
    },
    close() {
      void client?.then(c => c.close(), () => {})
    },
  }
}

function toolError(code: string, message: string, requestId?: unknown, conflicts?: unknown, data?: import('@vis/protocol').ErrorData) {
  const error = { code, message, ...(conflicts !== undefined ? { conflicts } : {}),
    ...(data?.reason !== undefined ? { reason: data.reason } : {}), ...(data?.params !== undefined ? { params: data.params } : {}),
    ...(data?.hint !== undefined ? { hint: data.hint } : {}) }
  return { content: [{ type: 'text', text: JSON.stringify({ error, ...(requestId === undefined ? {} : { requestId }) }) }], isError: true }
}

/** Reads stdin line by line and replies to each request; writes responses in completion order */
export async function serveMcp(env: Record<string, string | undefined>, input: AsyncIterable<string>, write: (line: string) => void): Promise<void> {
  const server = createMcpServer(env)
  const inflight = new Set<Promise<void>>()
  let buffer = ''
  const onLine = (line: string) => {
    if (!line.trim()) return
    let message: JsonRpcMessage
    try {
      message = JSON.parse(line)
    } catch {
      write(`${JSON.stringify({ jsonrpc: '2.0', id: null, error: { code: -32700, message: 'Cannot parse JSON' } })}\n`)
      return
    }
    const task = server.handle(message).then(response => { if (response) write(`${JSON.stringify(response)}\n`) })
    inflight.add(task)
    void task.finally(() => inflight.delete(task))
  }
  for await (const chunk of input) {
    buffer += chunk
    for (let nl = buffer.indexOf('\n'); nl >= 0; nl = buffer.indexOf('\n')) {
      onLine(buffer.slice(0, nl))
      buffer = buffer.slice(nl + 1)
    }
  }
  onLine(buffer)
  await Promise.all(inflight)
  server.close()
}
