import { afterEach, describe, expect, it, vi } from 'vitest'
import type { NodeView, TimelineDoc } from '@vis/protocol'
import type { TimelineEditorHost } from './types'
import { createTimelineDraft } from './draft'

const doc = (name = 'Initial'): TimelineDoc => ({ version: 1, tracks: [{ id: 'video', kind: 'video', name, muted: false, volume: 1, clips: [] }] })
const node = (document = doc(), revision = 1): NodeView => ({
  nodeId: 'timeline', kind: 'timeline', x: 0, y: 0, w: 300, h: 200, z: 0, layoutRevision: 1,
  slots: [{ slotId: 'slot', slotKey: 'main', revision, contentType: 'timeline', content: { type: 'timeline', doc: document } }],
})
function host(): TimelineEditorHost {
  return { node: node(), nodes: [], assetUrl: id => id, filmstripUrl: id => id, assetInfo: vi.fn(async () => ({})),
    preview: vi.fn(), commit: vi.fn(async () => 'ok' as const), export: vi.fn(), download: vi.fn(), showOnCanvas: vi.fn(), onClose: vi.fn() }
}
async function settle() { for (let i = 0; i < 8; i++) await Promise.resolve() }
afterEach(() => { vi.useRealTimers() })

describe('timeline draft saves', () => {
  it.each(['invalid_params', 'not_found', 'forbidden'])('retains %s failures without automatic retries', async code => {
    vi.useFakeTimers()
    const h = host()
    const failure = { code, data: { code } }
    h.commit = vi.fn().mockRejectedValue(failure)
    const controller = createTimelineDraft(h)
    controller.getSnapshot().edit(doc('Mine'), { immediate: true })
    await settle()
    await vi.advanceTimersByTimeAsync(120_000)
    expect(h.commit).toHaveBeenCalledTimes(1)
    expect(controller.getSnapshot()).toMatchObject({ doc: doc('Mine'), saveState: 'unsaved', saveError: failure })
    controller.dispose()
  })
  it.each([{ code: 'timeout' }, { code: 'unavailable' }, { data: { code: 'unavailable', reason: 'host.studiod_disconnected' } }])('retries transient RPC failures: %j', async failure => {
    vi.useFakeTimers()
    const h = host()
    h.commit = vi.fn().mockRejectedValueOnce(failure).mockResolvedValue('ok')
    const controller = createTimelineDraft(h)
    controller.getSnapshot().edit(doc('Mine'), { immediate: true })
    await settle()
    await vi.advanceTimersByTimeAsync(1000)
    expect(h.commit).toHaveBeenCalledTimes(2)
    expect(controller.getSnapshot().saveState).toBe('saved')
    controller.dispose()
  })
  it('debounces typing at 500ms and commits immediate edits at once', async () => {
    vi.useFakeTimers()
    const h = host()
    const controller = createTimelineDraft(h)
    controller.getSnapshot().edit(doc('Typed'))
    await vi.advanceTimersByTimeAsync(499)
    expect(h.commit).not.toHaveBeenCalled()
    controller.getSnapshot().edit(doc('Typed again'))
    await vi.advanceTimersByTimeAsync(500)
    expect(h.commit).toHaveBeenCalledExactlyOnceWith(doc('Typed again'), 1)
    expect(controller.getSnapshot().saveState).toBe('saved')
    controller.getSnapshot().edit(doc('Pointer'), { immediate: true })
    expect(h.commit).toHaveBeenLastCalledWith(doc('Pointer'), 2)
    await settle()
    controller.dispose()
  })
  it('batches later edits while a commit is in flight', async () => {
    const h = host()
    let resolve!: (result: 'ok') => void
    h.commit = vi.fn().mockImplementationOnce(() => new Promise(r => { resolve = r })).mockResolvedValue('ok')
    const controller = createTimelineDraft(h)
    controller.getSnapshot().edit(doc('First'), { immediate: true })
    controller.getSnapshot().edit(doc('Second'), { immediate: true })
    controller.getSnapshot().edit(doc('Third'), { immediate: true })
    expect(h.commit).toHaveBeenCalledTimes(1)
    resolve('ok')
    await settle()
    expect(h.commit).toHaveBeenCalledTimes(2)
    expect(h.commit).toHaveBeenLastCalledWith(doc('Third'), 2)
    expect(controller.getSnapshot().saveState).toBe('saved')
    controller.dispose()
  })
  it('enters conflict, blocks edits, updates theirs, and clears history on load', async () => {
    const h = host()
    h.commit = vi.fn(async () => 'conflict' as const)
    const controller = createTimelineDraft(h)
    controller.getSnapshot().edit(doc('Mine'), { immediate: true })
    await settle()
    controller.updateHost({ ...h, node: node(doc('Theirs'), 2) })
    expect(controller.getSnapshot()).toMatchObject({ saveState: 'conflict', conflict: { theirs: doc('Theirs'), revision: 2 } })
    controller.getSnapshot().edit(doc('Blocked'))
    expect(controller.getSnapshot().doc).toEqual(doc('Mine'))
    controller.getSnapshot().loadTheirs()
    expect(controller.getSnapshot()).toMatchObject({ doc: doc('Theirs'), baseRevision: 2, conflict: null, canUndo: false, canRedo: false, saveError: null })
    controller.dispose()
  })
  it('silently adopts outside changes until the first local edit', async () => {
    const h = host()
    const controller = createTimelineDraft(h)
    controller.updateHost({ ...h, node: node(doc('Outside'), 2) })
    expect(controller.getSnapshot()).toMatchObject({ doc: doc('Outside'), baseRevision: 2, conflict: null })
    controller.getSnapshot().edit(doc('Mine'), { immediate: true })
    await settle()
    controller.updateHost({ ...h, node: node(doc('Mine'), 3) })
    expect(controller.getSnapshot().conflict).toBeNull()
    controller.updateHost({ ...h, node: node(doc('Outside again'), 4) })
    expect(controller.getSnapshot().saveState).toBe('conflict')
    controller.dispose()
  })
  it('recognizes its own revision event before the commit resolves', async () => {
    const h = host()
    let resolve!: (result: 'ok') => void
    h.commit = vi.fn(() => new Promise<'ok'>(r => { resolve = r }))
    const controller = createTimelineDraft(h)
    controller.getSnapshot().edit(doc('Mine'), { immediate: true })
    controller.updateHost({ ...h, node: node(doc('Mine'), 2) })
    expect(controller.getSnapshot().conflict).toBeNull()
    resolve('ok')
    await settle()
    expect(controller.getSnapshot()).toMatchObject({ saveState: 'saved', baseRevision: 2 })
    controller.dispose()
  })
  it('undoes committed edits by committing their predecessor as a new revision, then redoes', async () => {
    const h = host()
    const controller = createTimelineDraft(h)
    controller.getSnapshot().edit(doc('Mine'), { immediate: true })
    await settle()
    controller.getSnapshot().undo()
    await settle()
    expect(h.commit).toHaveBeenLastCalledWith(doc(), 2)
    expect(controller.getSnapshot()).toMatchObject({ canRedo: true, canUndo: false, baseRevision: 3 })
    controller.getSnapshot().redo()
    await settle()
    expect(h.commit).toHaveBeenLastCalledWith(doc('Mine'), 3)
    controller.dispose()
  })
  it('retries a non-conflict failure with backoff while retaining the local document', async () => {
    vi.useFakeTimers()
    const h = host()
    const failure = { data: { code: 'unavailable', reason: 'media.preview_unavailable' } }
    h.commit = vi.fn().mockRejectedValueOnce(failure).mockResolvedValue('ok')
    const controller = createTimelineDraft(h)
    controller.getSnapshot().edit(doc('Mine'), { immediate: true })
    await settle()
    expect(controller.getSnapshot()).toMatchObject({ doc: doc('Mine'), saveState: 'unsaved', saveError: failure })
    await vi.advanceTimersByTimeAsync(999)
    expect(h.commit).toHaveBeenCalledTimes(1)
    await vi.advanceTimersByTimeAsync(1)
    expect(h.commit).toHaveBeenCalledTimes(2)
    expect(controller.getSnapshot()).toMatchObject({ saveState: 'saved', saveError: null })
    controller.dispose()
  })
  it('flushes a pending debounce and waits for the committed revision', async () => {
    vi.useFakeTimers()
    const h = host()
    const controller = createTimelineDraft(h)
    controller.getSnapshot().edit(doc('Mine'))
    await controller.getSnapshot().flush()
    expect(h.commit).toHaveBeenCalledExactlyOnceWith(doc('Mine'), 1)
    expect(controller.getSnapshot().saveState).toBe('saved')
    controller.dispose()
  })
  it('rejects flush with the save error and never retries a conflict', async () => {
    vi.useFakeTimers()
    const h = host()
    const failure = { message: 'Transport unavailable' }
    h.commit = vi.fn().mockRejectedValue(failure)
    const controller = createTimelineDraft(h)
    controller.getSnapshot().edit(doc('Mine'))
    await expect(controller.getSnapshot().flush()).rejects.toBe(failure)
    controller.dispose()
    const conflictHost = { ...host(), commit: vi.fn(async () => 'conflict' as const) }
    const conflicted = createTimelineDraft(conflictHost)
    conflicted.getSnapshot().edit(doc('Mine'), { immediate: true })
    await settle()
    await vi.advanceTimersByTimeAsync(60_000)
    expect(conflictHost.commit).toHaveBeenCalledTimes(1)
    conflicted.dispose()
  })
  it('keeps typing debounced when an earlier in-flight commit completes', async () => {
    vi.useFakeTimers()
    const h = host()
    let resolve!: (result: 'ok') => void
    h.commit = vi.fn().mockImplementationOnce(() => new Promise<'ok'>(r => { resolve = r })).mockResolvedValue('ok')
    const controller = createTimelineDraft(h)
    controller.getSnapshot().edit(doc('First'), { immediate: true })
    controller.getSnapshot().edit(doc('Typing'))
    resolve('ok')
    await settle()
    expect(h.commit).toHaveBeenCalledTimes(1)
    await vi.advanceTimersByTimeAsync(500)
    expect(h.commit).toHaveBeenLastCalledWith(doc('Typing'), 2)
    controller.dispose()
  })
  it('queues undo during a save even when undo returns to the previously saved document', async () => {
    const h = host()
    let resolve!: (result: 'ok') => void
    h.commit = vi.fn().mockImplementationOnce(() => new Promise<'ok'>(r => { resolve = r })).mockResolvedValue('ok')
    const controller = createTimelineDraft(h)
    controller.getSnapshot().edit(doc('First'), { immediate: true })
    controller.getSnapshot().undo()
    resolve('ok')
    await settle()
    expect(h.commit).toHaveBeenLastCalledWith(doc(), 2)
    expect(controller.getSnapshot().saveState).toBe('saved')
    controller.dispose()
  })
  it('clears a retry error when undo returns to the saved document', async () => {
    vi.useFakeTimers()
    const h = host()
    h.commit = vi.fn().mockRejectedValue({ message: 'Transport unavailable' })
    const controller = createTimelineDraft(h)
    controller.getSnapshot().edit(doc('First'), { immediate: true })
    await settle()
    controller.getSnapshot().undo()
    await settle()
    expect(controller.getSnapshot()).toMatchObject({ saveState: 'saved', saveError: null, doc: doc() })
    await vi.advanceTimersByTimeAsync(60_000)
    expect(h.commit).toHaveBeenCalledTimes(1)
    controller.dispose()
  })
  it('does not load a stale host document after a conflict response', async () => {
    const h = { ...host(), commit: vi.fn(async () => 'conflict' as const) }
    const controller = createTimelineDraft(h)
    controller.getSnapshot().edit(doc('Mine'), { immediate: true })
    await settle()
    controller.getSnapshot().loadTheirs()
    expect(controller.getSnapshot().doc).toEqual(doc('Mine'))
    expect(controller.getSnapshot().saveState).toBe('conflict')
    controller.updateHost({ ...h, node: node(doc('Theirs'), 2) })
    controller.getSnapshot().loadTheirs()
    expect(controller.getSnapshot().doc).toEqual(doc('Theirs'))
    controller.dispose()
  })
  it('does not treat schema key ordering as a change', () => {
    const h = host()
    const controller = createTimelineDraft(h)
    controller.getSnapshot().edit({ tracks: [{ name: 'Initial', clips: [], volume: 1, muted: false, kind: 'video', id: 'video' }], version: 1 }, { immediate: true })
    expect(controller.getSnapshot().canUndo).toBe(false)
    expect(h.commit).not.toHaveBeenCalled()
    controller.dispose()
  })
})
