import { and, eq, inArray, lte, sql } from 'drizzle-orm'
import { ApprovalPayload } from '@vis/protocol'
import { appendEvent, currentSeq, type SpaceTx } from './events'
import type { SpaceDb } from './open'
import * as s from './schema/space'

type LegacyFrameApproval = Omit<ApprovalPayload, 'kind'> & { kind: 'canvas_outside_frame'; nodeIds?: string[] }

export function workspaceMigrationBoundary(tx: SpaceTx) {
  return tx.select({ eventSeq: s.contractMigrations.eventSeq, idempotencyRowid: s.contractMigrations.idempotencyRowid })
    .from(s.contractMigrations).where(eq(s.contractMigrations.id, '0010')).get()
}

export function isLegacyWorkspaceRequest(tx: SpaceTx, requestId: string): boolean {
  const boundary = workspaceMigrationBoundary(tx)
  if (!boundary) return false
  return !!tx.select({ requestId: s.idempotencyKeys.requestId }).from(s.idempotencyKeys)
    .where(and(eq(s.idempotencyKeys.requestId, requestId), lte(sql`${s.idempotencyKeys}.rowid`, boundary.idempotencyRowid))).get()
}

/** Idempotent upgrade of legacy JSON data for 0010; structural migrations are generated by drizzle. */
export function migrateWorkspaces(db: SpaceDb): void {
  db.transaction(tx => {
    if (workspaceMigrationBoundary(tx)) return
    tx.update(s.workItems).set({ reviewBy: 'parent' }).where(sql`${s.workItems.reviewBy} = 'coordinator'`).run()
    tx.update(s.workMessages).set({ to: 'parent' }).where(sql`${s.workMessages.to} = 'coordinator'`).run()
    tx.update(s.workMessages).set({ to: 'child' }).where(sql`${s.workMessages.to} = 'worker'`).run()
    tx.update(s.workMessages).set({ from: sql`json_remove(${s.workMessages.from}, '$.role')` })
      .where(sql`json_type(${s.workMessages.from}, '$.role') IS NOT NULL`).run()
    tx.update(s.nodes).set({ frame: sql`json_remove(${s.nodes.frame}, '$.workItemId')` })
      .where(sql`json_type(${s.nodes.frame}, '$.workItemId') IS NOT NULL`).run()

    const at = Date.now()
    for (const row of tx.select().from(s.transcriptEntries).where(and(eq(s.transcriptEntries.kind, 'approval'),
      sql`json_extract(${s.transcriptEntries.payload}, '$.kind') = 'canvas_outside_frame'`)).all()) {
      const old = row.payload as LegacyFrameApproval
      const expired = old.status === 'pending' || (old.status === 'approved' && old.decision === 'allow_session')
      const { nodeIds: _, ...previous } = old
      const payload = ApprovalPayload.parse({ ...previous, kind: 'other', summary: `旧画布框外审批（已停用）：${old.summary}`,
        ...(expired ? { status: 'expired', decision: 'deny' } : {}) })
      const revision = row.revision + 1
      tx.update(s.transcriptEntries).set({ payload, revision, updatedAt: at })
        .where(and(eq(s.transcriptEntries.sessionId, row.sessionId), eq(s.transcriptEntries.itemId, row.itemId))).run()
      appendEvent(tx, { type: 'transcript.itemUpserted', entityType: 'session', entityId: row.sessionId,
        payload: { itemId: row.itemId, createdSeq: row.createdSeq, revision, turnId: row.turnId, kind: row.kind, payload, createdAt: row.createdAt, updatedAt: at } }, at)
      if (old.status === 'pending' && row.turnId) {
        const denied = tx.update(s.turns).set({ status: 'failed', endedAt: at })
          .where(and(eq(s.turns.id, row.turnId), inArray(s.turns.status, ['running', 'waiting_user']))).returning().get()
        if (denied) {
          tx.update(s.sessions).set({ queuePaused: true }).where(eq(s.sessions.id, row.sessionId)).run()
          appendEvent(tx, { type: 'turn.stateChanged', entityType: 'turn', entityId: row.turnId, payload: { turnId: row.turnId, status: 'failed' } }, at)
        }
      }
    }

    // Legacy undo records can only restore canvas content, not reestablish workspace bindings.
    for (const row of tx.select().from(s.undoEntries).all()) {
      const old = row.inverse as { steps: { kind: string }[]; workFrames?: unknown }
      if (!('workFrames' in old) && !old.steps.some(step => step.kind === 'frameBinding')) continue
      const { workFrames: _, ...history } = old
      tx.update(s.undoEntries).set({ inverse: { ...history, steps: old.steps.filter(step => step.kind !== 'frameBinding') } })
        .where(eq(s.undoEntries.id, row.id)).run()
    }
    // rowid partitions existing caches without relying on timestamps that may repeat or move backward.
    // shortcut: Idempotency records are append-only; switch to per-record version markers when introducing cleanup or table rebuilding.
    const idempotencyRowid = tx.select({ rowid: sql<number>`coalesce(max(${s.idempotencyKeys}.rowid), 0)` }).from(s.idempotencyKeys).get()!.rowid
    tx.insert(s.contractMigrations).values({ id: '0010', eventSeq: currentSeq(tx), idempotencyRowid }).run()
  })
}
