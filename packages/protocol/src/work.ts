import { z } from 'zod'
import { CanvasNodeKind, Id, RequestId, Revision } from './common'
import { AgentKind, ApprovalStatus } from './session'

// Contracts for work items, dispatch and message recall; see docs/rfc/0009.

export const WorkStatus = z.enum(['todo', 'in_progress', 'in_review', 'done'])
export type WorkStatus = z.infer<typeof WorkStatus>

export const ReviewBy = z.enum(['user', 'parent'])
export type ReviewBy = z.infer<typeof ReviewBy>

export const WorkMessageKind = z.enum(['brief', 'done', 'question', 'blocked', 'escalation', 'reply', 'review_feedback', 'recall', 'deleted', 'failure'])
export type WorkMessageKind = z.infer<typeof WorkMessageKind>

// Messages Agents can send via work.report; question / blocked / escalation require replies and copy the user.
export const WorkReportKind = z.enum(['done', 'question', 'blocked', 'escalation'])
export type WorkReportKind = z.infer<typeof WorkReportKind>

export const WorkActor = z.discriminatedUnion('kind', [
  z.object({ kind: z.literal('user') }),
  z.object({ kind: z.literal('agent'), sessionId: Id }),
])
export type WorkActor = z.infer<typeof WorkActor>

export const WorkFailure = z.object({
  sessionId: Id, turnId: Id,
  reason: z.enum(['agent_start_failed', 'ref_unresolvable', 'dispatch_rejected', 'dispatch_unknown', 'turn_failed', 'runtime_exited', 'runtime_restarted', 'turn_silent', 'turn_unreported']),
  detail: z.string().optional(),
})
export type WorkFailure = z.infer<typeof WorkFailure>

export const WorkMessageFrom = z.discriminatedUnion('kind', [
  z.object({ kind: z.literal('user') }),
  z.object({ kind: z.literal('session'), sessionId: Id }),
  // Records generated by the state machine itself, such as recall
  z.object({ kind: z.literal('system'), failure: WorkFailure.optional() }),
])
export type WorkMessageFrom = z.infer<typeof WorkMessageFrom>

export const WorkMessageTo = z.enum(['parent', 'child', 'user'])
export type WorkMessageTo = z.infer<typeof WorkMessageTo>

export const WorkRefs = z.object({
  nodeIds: z.array(Id).max(50).optional(),
  assetVersionIds: z.array(Id).max(50).optional(),
})
export type WorkRefs = z.infer<typeof WorkRefs>

// Card status dot: active has a running turn, waiting has an unresolved question, error means the latest turn failed, idle otherwise.
export const WorkActivity = z.enum(['active', 'idle', 'waiting', 'error'])
export type WorkActivity = z.infer<typeof WorkActivity>

// Canvas frame colors use a fixed palette, mapped to theme colors by the UI.
export const FrameColor = z.enum(['gray', 'blue', 'teal', 'green', 'amber', 'orange', 'red', 'violet'])
export type FrameColor = z.infer<typeof FrameColor>

export const Rect = z.object({ x: z.number(), y: z.number(), w: z.number().positive(), h: z.number().positive() })
export type Rect = z.infer<typeof Rect>

export const WorkSessionView = z.object({
  silentSince: z.int().nullable().default(null),
  sessionId: Id,
  agentKind: AgentKind,
  title: z.string(),
  activeTurnId: Id.nullable(),
  // One-line summary of current activity, e.g. "Generating video - 68%" or "Waiting for your reply"; null if absent.
  doing: z.string().nullable(),
  lastActivityAt: z.int().nullable(),
  archived: z.boolean(),
})
export type WorkSessionView = z.infer<typeof WorkSessionView>

export const WorkItemView = z.object({
  workItemId: Id,
  spaceId: Id,
  // Returned only for scope: 'all'
  spaceName: z.string().optional(),
  parentId: Id.nullable(),
  childIds: z.array(Id),
  title: z.string(),
  brief: z.string(),
  status: WorkStatus,
  pinned: z.boolean(),
  reviewBy: ReviewBy,
  workDir: z.string(),
  createdBy: WorkActor,
  revision: Revision,
  activationSeq: z.int().nonnegative().nullable(),
  waitingSlotSince: z.int().nullable(),
  // Feedback retained after rejection or reopening when slots are full, delivered together on activation.
  pendingFeedback: z.boolean(),
  // Completion report for the current review; null for manual user submission.
  reviewReportId: Id.nullable(),
  activity: WorkActivity,
  failure: WorkFailure.nullable().optional(),
  // Ordered by session creation time ascending; the first unarchived session is the main session.
  sessions: z.array(WorkSessionView),
  unreadCount: z.int().nonnegative(),
  unresolvedCount: z.int().nonnegative(),
  // Earliest unresolved question, blocked or escalation message; the card shows "Waiting for reply - summary".
  waitingOn: z.object({ messageId: Id, kind: z.enum(['question', 'blocked', 'escalation']), excerpt: z.string().max(80) }).nullable(),
  todayGenerations: z.int().nonnegative(),
  // Count of nodes changed by sessions since this activation, deduplicated by node.
  changeCount: z.int().nonnegative(),
  // Latest canvas event sequence in this activation's changes; null if there are no changes.
  lastChangeSeq: z.int().nonnegative().nullable(),
  statusChangedAt: z.int(),
  createdAt: z.int(),
  archivedAt: z.int().nullable(),
})
export type WorkItemView = z.infer<typeof WorkItemView>

export const WorkMessageView = z.object({
  messageId: Id,
  workItemId: Id,
  kind: WorkMessageKind,
  from: WorkMessageFrom,
  to: WorkMessageTo,
  body: z.string(),
  refs: WorkRefs,
  replyTo: Id.nullable(),
  deliveryId: Id.nullable(),
  // Only question / blocked / escalation: the reply, recall or deleted record resolving it.
  resolvedBy: Id.nullable(),
  // Redelivered batches, marked as such during injection.
  redelivered: z.boolean(),
  createdAt: z.int(),
  deliveredAt: z.int().nullable(),
  ackedAt: z.int().nullable(),
  readAt: z.int().nullable(),
})
export type WorkMessageView = z.infer<typeof WorkMessageView>

export const WorkInboxGroup = z.object({
  spaceId: Id,
  spaceName: z.string(),
  items: z.array(z.object({
    workItemId: Id,
    title: z.string(),
    status: WorkStatus,
    parentTitle: z.string().nullable(),
    messages: z.array(WorkMessageView),
    // Display names for nodes in message refs (frame title, first text line, or media kind plus first prompt line); deleted nodes use "Deleted node".
    nodeLabels: z.record(Id, z.string()),
  })),
})
export type WorkInboxGroup = z.infer<typeof WorkInboxGroup>

export const WorkInboxCounts = z.object({
  unread: z.int().nonnegative(),
  unresolved: z.int().nonnegative(),
  bySpace: z.array(z.object({ spaceId: Id, unread: z.int().nonnegative(), unresolved: z.int().nonnegative() })),
})
export type WorkInboxCounts = z.infer<typeof WorkInboxCounts>

export const WorkSlotsView = z.object({
  used: z.int().nonnegative(),
  limit: z.int().positive(),
  bySpace: z.array(z.object({ spaceId: Id, used: z.int().nonnegative(), limit: z.int().positive().nullable() })),
  // Queue waiting for slots, ordered by waitingSince.
  queue: z.array(z.object({ spaceId: Id, workItemId: Id, title: z.string(), waitingSince: z.int() })),
})
export type WorkSlotsView = z.infer<typeof WorkSlotsView>

export const WorkChange = z.object({
  // seq of this node's last canvas event in this activation; work.changes returns descending order by this value.
  lastSeq: z.int().nonnegative(),
  nodeId: Id,
  nodeKind: CanvasNodeKind,
  slotId: Id.nullable(),
  change: z.enum(['created', 'updated', 'deleted']),
  // Revision at the activation baseline; null for nodes created in this activation.
  fromRevision: Revision.nullable(),
  toRevision: Revision.nullable(),
  sessionId: Id.nullable(),
})
export type WorkChange = z.infer<typeof WorkChange>

// UI calls may include spaceId for cross-project operations, or omit it for the current project; Agent calls with spaceId are always forbidden.
const Space = { spaceId: Id.optional() }
const Transition = { requestId: RequestId, ...Space, workItemId: Id, expectedRevision: Revision.optional() }
const Queued = z.object({ item: WorkItemView, queued: z.boolean() })

export const work = {
  list: {
    params: z.object({ ...Space, status: WorkStatus.optional(), parentId: Id.optional(), scope: z.enum(['space', 'all']).optional() }),
    result: z.object({ items: z.array(WorkItemView) }),
  },
  inbox: {
    params: z.object({}),
    result: z.object({ groups: z.array(WorkInboxGroup), counts: WorkInboxCounts }),
  },
  get: {
    params: z.object({ ...Space, workItemId: Id.optional(), beforeCreatedAt: z.int().optional(), limit: z.int().min(1).max(200).optional() }),
    result: z.object({ item: WorkItemView, messages: z.array(WorkMessageView), hasMore: z.boolean() }),
  },
  create: {
    params: z.object({
      requestId: RequestId, ...Space, title: z.string().trim().min(1).max(60), brief: z.string().max(20_000).optional(), workDir: z.string().min(1).optional(),
      // Create a session and activate immediately (queue if slots are full); the board + omits this and stays in todo.
      chat: z.object({ agentKind: AgentKind }).optional(),
    }),
    result: Queued,
  },
  dispatch: {
    params: z.object({
      requestId: RequestId,
      ...Space,
      // Required for UI; Agents omit it and use their own work item.
      parentId: Id.optional(),
      title: z.string().trim().min(1).max(60),
      brief: z.string().min(1).max(20_000),
      agentKind: AgentKind,
      activate: z.boolean().optional(),
      reviewBy: ReviewBy.optional(),
    }),
    result: Queued,
  },
  // agentKind is required to create a session when the work item has none.
  activate: { params: z.object({ ...Transition, agentKind: AgentKind.optional() }), result: Queued },
  recall: {
    params: z.object(Transition),
    result: z.object({
      // All work items affected by this recall (including children when a parent cascades).
      items: z.array(WorkItemView),
      cancelledJobs: z.array(z.object({ jobId: Id, providerCancelled: z.boolean() })),
    }),
  },
  deletePlan: {
    params: z.object({ ...Space, workItemId: Id }),
    result: z.object({
      runningTurns: z.int().nonnegative(),
      unfinishedJobs: z.int().nonnegative(),
      childrenTotal: z.int().nonnegative(),
      childrenInProgress: z.int().nonnegative(),
      unresolvedMessages: z.int().nonnegative(),
      hasUnreviewedReport: z.boolean(),
      queued: z.boolean(),
      workDir: z.string(),
    }),
  },
  requestDelete: {
    params: z.strictObject({ requestId: RequestId, workItemIds: z.array(Id).min(1).max(20).refine(ids => new Set(ids).size === ids.length, { message: 'Work item IDs must be unique' }) }),
    result: z.object({ approvalId: Id, status: ApprovalStatus }),
  },
  // 0015: can only move under an unarchived root in the same project; the moved item must have no children; null restores root status.
  reparent: {
    params: z.object({ requestId: RequestId, ...Space, workItemId: Id, parentId: Id.nullable() }),
    result: z.object({ item: WorkItemView, oldParentId: Id.nullable() }),
  },
  delete: {
    params: z.object({ requestId: RequestId, ...Space, workItemId: Id }),
    result: z.object({
      workItemIds: z.array(Id),
      cancelledJobs: z.array(z.object({ jobId: Id, providerCancelled: z.boolean() })),
    }),
  },
  // Board dragging: users can move work items to any status without blocking, requiring a reason or interrupting active turns or generation.
  move: { params: z.object({ ...Transition, status: WorkStatus, agentKind: AgentKind.optional() }), result: Queued },
  reopen: { params: z.object({ ...Transition, resumeSessionId: Id.optional(), note: z.string().max(20_000).optional() }), result: Queued },
  submitReview: { params: z.object(Transition), result: WorkItemView },
  report: {
    params: z.strictObject({ requestId: RequestId, kind: WorkReportKind, body: z.string().trim().min(1).max(20_000), refs: WorkRefs.optional() }),
    result: z.object({ messageId: Id, item: WorkItemView }),
  },
  reply: {
    params: z.object({ requestId: RequestId, ...Space, workItemId: Id, replyTo: Id.optional(), body: z.string().trim().min(1).max(20_000), refs: WorkRefs.optional() }),
    result: z.object({ messageId: Id }),
  },
  review: {
    // Parent Agent rejection requires feedback (server-validated); user feedback is optional and its absence does not notify the Agent.
    // agentKind: choose an Agent when the user rejects a card that has never had a session.
    params: z.object({ ...Transition, decision: z.enum(['approve', 'reject']), feedback: z.string().trim().max(20_000).optional(), agentKind: AgentKind.optional() }),
    result: Queued,
  },
  update: {
    params: z.object({ requestId: RequestId, ...Space, workItemId: Id, expectedRevision: Revision, title: z.string().trim().min(1).max(60).optional(), brief: z.string().max(20_000).optional(), pinned: z.boolean().optional(), reviewBy: ReviewBy.optional() }),
    result: WorkItemView,
  },
  markRead: {
    params: z.object({ ...Space, workItemId: Id }),
    result: z.object({ marked: z.int().nonnegative() }),
  },
  changes: {
    params: z.object({ ...Space, workItemId: Id }),
    result: z.object({ baselineSeq: z.int().nonnegative().nullable(), changes: z.array(WorkChange) }),
  },
  slots: {
    params: z.object({}),
    result: WorkSlotsView,
  },
  setSlotLimit: {
    // Without spaceId, set the global limit; with spaceId, set the project limit, where null means unlimited.
    params: z.strictObject({ spaceId: Id.optional(), limit: z.int().min(1).max(32).nullable() })
      .refine(p => p.limit !== null || p.spaceId !== undefined, { message: 'Global limit cannot be unlimited', path: ['limit'] }),
    result: WorkSlotsView,
  },
} as const
