import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import type { AgentKind, AgentModelOption } from '@vis/protocol'
import type { SpaceDb } from '@vis/storage'
import { type AgentEvent, type AgentRuntimePort, type DispatchInput, DispatchError, type RequestApproval } from '../runtime-port'
import { exitInstance, markInstanceReady, startTurnInstance } from '../agent-instances'
import { type ChildLike, createRpcPeer, RpcRequestError, type SpawnFn } from '../stdio-rpc'
import { prepareSandbox } from '../sandbox'
import { agentPath } from '../agent-path'
import { agentInstructions, turnPrompt } from '../instructions'
import type { AcpAgentProfile, AcpPreparedTurn } from './profile'
import { createTranslator } from './translate'
import { configChoices, configOption, modelOption } from './config'
import { killTree, spawnAgentProcess } from '../kill-tree'
import { nodeChildEnv } from '../resolve-executable'

export const MCP_SERVER = 'vis'
export const ACP_PROTOCOL_VERSION = 1

export type AcpRuntimeOptions = {
  spawn?: SpawnFn
  /** Directory containing the vis command generated by studiod, added to the Agent PATH */
  cliBinDir?: string
  /** Packaged tools appended after the user PATH. */
  fallbackDirs?: readonly string[]
  /** Session working directory, also the ACP session cwd; resume must use the same directory */
  workDir(sessionId: string): string
  /** Parent directory for disposable model probes. */
  probeDir: string
  /** Issue a runtime token; store only its hash in the database */
  issueToken(): { token: string; tokenHash: string }
  socketPath: string
  /** Command to start the vis MCP server; command must be an absolute path */
  visMcp: { command: string; args: string[] }
  dataDir?: string
  forbiddenPaths?: readonly string[]
  /** Maximum wait from startup until session/prompt is sent */
  startTimeoutMs?: number
  /** Rejection within this interval after session/prompt is sent means nonreceipt; after it, assume acceptance */
  admissionMs?: number
  /** Maximum silence after admission, excluding time awaiting user approvals */
  inactivityTimeoutMs?: number
  /** Grace period for the Agent to exit during interruption or cleanup; stop the process immediately on timeout */
  interruptGraceMs?: number
  env?: Record<string, string | undefined>
  now?: () => number
}

type TurnStatus = 'completed' | 'failed' | 'interrupted'

type Run = {
  sessionId: string
  turnId: string
  instanceId: string
  child: ChildLike
  peer: ReturnType<typeof createRpcPeer>
  exited: Promise<void>
  finishing?: Promise<void>
  acpSessionId: string | null
  translate: ReturnType<typeof createTranslator> | null
  toolCalls: Map<string, Record<string, unknown>>
  permissionsExpanded: boolean
  accepted: boolean
  interrupted: boolean
  ended: boolean
  /** Updates received before acceptance, processed in order after acceptance */
  backlog: any[]
  onFirstUpdate: (() => void) | undefined
  inactivityTimer?: ReturnType<typeof setTimeout>
  pendingApprovals: number
  done: Promise<void>
  resolveDone(): void
}

/**
 * Start one ACP Agent process per turn: handshake, create or resume a session, and send the prompt; close the session and exit the process when the turn ends.
 * ACP session/prompt responds only at turn completion, with no separate receipt acknowledgement:
 * rejection shortly after sending means nonreceipt; the first update or expiry of that interval means acceptance (0005).
 */
export function createAcpRuntime(
  ctx: { db: SpaceDb; report: (event: AgentEvent) => void; requestApproval?: RequestApproval },
  opts: AcpRuntimeOptions,
  profile: AcpAgentProfile,
): AgentRuntimePort & { agentOptions(agentKind: AgentKind, options?: { model?: string }): Promise<AgentModelOption[]>; dispose(): Promise<void> } {
  const { db, report } = ctx
  const now = opts.now ?? Date.now
  const spawn = opts.spawn ?? spawnAgentProcess
  const grace = () => new Promise<void>(r => setTimeout(r, opts.interruptGraceMs ?? 5000).unref())
  const runs = new Map<string, Run>()
  const processes = new Set<Run>()
  const startingChildren = new Set<ChildLike>()
  let defaultModel: string | undefined
  let disposed = false

  const exit = (instanceId: string, reason: string) => exitInstance(db, instanceId, reason, now())

  function prepare(sessionId: string, skillsPath?: string, work?: DispatchInput['workContext'], dir = opts.workDir(sessionId)) {
    mkdirSync(dir, { recursive: true })
    const sandbox = prepareSandbox({ cwd: dir, agent: opts.forbiddenPaths ? { ...profile.sandbox, forbiddenPaths: opts.forbiddenPaths } : profile.sandbox, ...(opts.dataDir ? { dataDir: opts.dataDir } : {}), ...(opts.env ? { env: opts.env } : {}) })
    sandbox.env.PATH = agentPath({ cliBinDir: opts.cliBinDir, fallbackDirs: opts.fallbackDirs, base: sandbox.env.PATH })
    const prepared: AcpPreparedTurn = { sessionId, cwd: dir, sandbox, ...(skillsPath ? { skillsPath } : {}), ...(work ? { work } : {}) }
    const files = profile.sessionFiles?.(prepared) ?? []
    for (const file of files) {
      mkdirSync(dirname(file.path), { recursive: true })
      writeIfChanged(file.path, file.content)
    }
    return { ...prepared, files }
  }

  function launch(prepared: AcpPreparedTurn) {
    const { cwd, sandbox } = prepared
    const { command, args } = profile.launch(prepared)
    const child = sandbox.policy
      ? spawn('/usr/bin/sandbox-exec', ['-p', sandbox.policy, command, ...args], { cwd, env: sandbox.env })
      : spawn(command, args, { cwd, env: { ...sandbox.env, ...nodeChildEnv(command) } })
    // Do not log raw third-party diagnostics, which may expose configuration or credentials; stdout carries only the protocol.
    child.stderr?.resume()
    startingChildren.add(child)
    return child
  }

  async function closeSession(peer: ReturnType<typeof createRpcPeer>, sessionId: string | null) {
    if (!peer.closed && sessionId) await Promise.race([peer.request('session/close', { sessionId }).catch(() => {}), grace()])
  }

  function activity(run: Run) {
    clearTimeout(run.inactivityTimer)
    if (!run.accepted || run.ended || run.interrupted || run.pendingApprovals > 0 || disposed) return
    run.inactivityTimer = setTimeout(() => {
      report({ type: 'item', sessionId: run.sessionId, turnId: run.turnId, itemId: `${profile.itemPrefix}:${run.acpSessionId}:${run.turnId}:inactive`, revision: 1, kind: 'notice', payload: { code: 'agent_inactive', message: 'The Agent sent no activity for too long. This turn failed and its process was stopped.' } })
      void terminate(run, 'failed')
    }, opts.inactivityTimeoutMs ?? 600_000).unref()
  }

  function handleUpdate(run: Run, params: any) {
    if (params?.sessionId !== run.acpSessionId || !run.translate) return
    activity(run)
    const update = params.update
    if (update?.toolCallId && ['tool_call', 'tool_call_update'].includes(update.sessionUpdate)) {
      run.toolCalls.set(update.toolCallId, { ...run.toolCalls.get(update.toolCallId), ...update })
    }
    if (!run.accepted) {
      run.backlog.push(params.update)
      run.onFirstUpdate?.()
      return
    }
    if (run.ended) return
    for (const item of run.translate(params.update)) report({ type: 'item', sessionId: run.sessionId, turnId: run.turnId, ...item })
  }

  async function handleRequest(run: Run, method: string, params: any): Promise<unknown> {
    if (method === 'session/request_permission') {
      const options: { optionId: string; kind: string }[] = Array.isArray(params?.options) ? params.options : []
      // Some Agents send only IDs in approvals; recover details from earlier tool updates.
      const tool = { ...run.toolCalls.get(params?.toolCall?.toolCallId), ...params?.toolCall }
      let decision = 'deny'
      const { kind, cwd, paths, autoApprovalBlocked, visTool } = profile.classifyTool(tool, opts.workDir(run.sessionId))
      const mutating = ['execute', 'edit', 'delete', 'move'].includes(kind)
      const readOnlySafe = kind === 'read' || (profile.readOnlyEnforcedByAgent === true && !mutating)
      if (visTool === true && !mutating && !disposed && !run.ended && !run.interrupted && params?.sessionId === run.acpSessionId) {
        decision = 'allow_once'
      } else if (ctx.requestApproval && (run.permissionsExpanded || readOnlySafe) && !disposed && !run.ended && !run.interrupted && params?.sessionId === run.acpSessionId) {
        run.pendingApprovals++
        clearTimeout(run.inactivityTimer)
        try {
          const detail = JSON.stringify({ kind: tool?.kind, title: tool?.title, rawInput: tool?.rawInput, content: tool?.content, locations: tool?.locations, ...(tool?.rawInput === undefined && !tool?.content?.length && !tool?.locations?.length ? { toolCallId: tool?.toolCallId } : {}) }, null, 2)
          decision = await ctx.requestApproval({ sessionId: run.sessionId, turnId: run.turnId, kind: kind === 'execute' ? 'command' : ['edit', 'delete', 'move'].includes(kind) ? 'file_write' : kind === 'fetch' ? 'network' : 'other', summary: tool?.title || profile.permissionSummary || `${profile.label} requests tool permission`, detail,
            ...(cwd === undefined ? {} : { cwd }), ...(paths ? { paths } : {}),
            ...(autoApprovalBlocked ? { autoApprovalBlocked: true } : {}),
            ...(kind === 'fetch' ? { webRead: true } : {}),
          })
        } catch {
          // Stay denied if the connection or approval fails.
        } finally {
          run.pendingApprovals--
          activity(run)
        }
      }
      if (disposed || run.ended || run.interrupted) decision = 'deny'
      // The core reuses session grants; ACP allow_always may persist beyond the session.
      const selected = options.find(o => o.kind === (decision === 'deny' ? 'reject_once' : 'allow_once'))
        ?? options.find(o => o.kind === 'reject_once' || o.kind === 'reject_always')
      return { outcome: selected ? { outcome: 'selected', optionId: selected.optionId } : { outcome: 'cancelled' } }
    }
    throw new RpcRequestError(-32601, `Unsupported request: ${method}`)
  }

  /** Close the session so the Agent flushes to disk, then stop the process; only then report turn completion so the next resume finds the session no longer in use */
  function finish(run: Run, status: TurnStatus): Promise<void> {
    // A second caller, such as process exit during a prompt ending, must wait too: disposal closes the database after `done`.
    if (run.ended) return run.finishing ?? Promise.resolve()
    run.ended = true
    clearTimeout(run.inactivityTimer)
    run.finishing = (async () => {
      await closeSession(run.peer, run.acpSessionId)
      await stop(run, true)
      if (runs.get(run.sessionId) === run) runs.delete(run.sessionId)
      exit(run.instanceId, status)
      report({ type: 'turn_ended', sessionId: run.sessionId, turnId: run.turnId, status })
    })()
    return run.finishing
  }

  async function stop(run: Pick<Run, 'child' | 'exited'>, force = false) {
    // Session close has already allowed a flush. Kill the owned group before EOF can let its leader exit alone.
    if (force) { await killTree(run.child, 'SIGKILL'); return }
    try {
      run.child.stdin.end()
    } catch {
      // Process already exited
    }
    await Promise.race([run.exited, grace()])
    await killTree(run.child)
  }

  async function terminate(run: Run, status: 'failed' | 'interrupted') {
    if (run.ended) return run.finishing
    run.interrupted = status === 'interrupted'
    run.ended = true
    clearTimeout(run.inactivityTimer)
    const killed = killTree(run.child, 'SIGKILL')
    run.finishing = killed
    if (runs.get(run.sessionId) === run) runs.delete(run.sessionId)
    exit(run.instanceId, status)
    report({ type: 'turn_ended', sessionId: run.sessionId, turnId: run.turnId, status })
    await killed
    run.resolveDone()
  }

  async function terminateTurn({ sessionId, turnId }: { sessionId: string; turnId: string }) {
    const run = runs.get(sessionId)
    if (run?.turnId === turnId) await terminate(run, 'interrupted')
  }

  return {
    terminateTurn,
    async ensureReady(sessionId) {
      mkdirSync(opts.workDir(sessionId), { recursive: true })
    },

    async agentOptions(agentKind) {
      if (disposed) throw new Error(`${profile.label} runtime is closed`)
      if (agentKind !== profile.kind) throw new Error(`${profile.label} does not support this Agent`)
      if (!profile.config.model) return []
      const probeId = `model-options-${randomUUID()}`
      const prepared = prepare(probeId, undefined, undefined, join(opts.probeDir, probeId))
      let child: ChildLike | undefined
      let peer: ReturnType<typeof createRpcPeer> | undefined
      let acpSessionId: string | null = null
      let exited = Promise.resolve()
      let probeExited = false
      let timer: ReturnType<typeof setTimeout> | undefined
      try {
        child = launch(prepared)
        let rejectClosed!: (error: Error) => void
        const closed = new Promise<never>((_, reject) => { rejectClosed = reject })
        closed.catch(() => {})
        exited = new Promise<void>(resolve => {
          child!.once('exit', () => { probeExited = true; resolve() })
          child!.once('error', () => {
            if (child!.pid === undefined) { probeExited = true; resolve() }
          })
        })
        child.once('error', rejectClosed)
        child.once('exit', () => rejectClosed(new Error(`${profile.processLabel} has exited`)))
        peer = createRpcPeer({ input: child.stdout, output: child.stdin }, {
          onNotification: () => {},
          onRequest: method => { throw new RpcRequestError(-32601, `Unsupported request: ${method}`) },
          onClose: () => rejectClosed(new Error(`${profile.processLabel} connection is closed`)),
        })
        const timeout = new Promise<never>((_, reject) => { timer = setTimeout(() => reject(new Error(`Timed out reading the ${profile.label} model list`)), opts.startTimeoutMs ?? 60_000) })
        const step = <T>(request: Promise<T>) => Promise.race([request, closed, timeout])
        await step(peer.request('initialize', {
          protocolVersion: ACP_PROTOCOL_VERSION,
          clientCapabilities: { fs: { readTextFile: false, writeTextFile: false }, terminal: false },
          clientInfo: { name: 'vis-creative', version: '0.0.0' },
        }))
        const session = await step(peer.request('session/new', { cwd: prepared.cwd, mcpServers: [] }))
        acpSessionId = session?.sessionId
        const model = configOption(session?.configOptions, profile.config.model)
        const choices = configChoices(model)
        if (!acpSessionId || !model || !choices.length) throw new Error(`${profile.label} returned no available models`)
        defaultModel = model.currentValue
        const models: AgentModelOption[] = []
        let refusal: Error | undefined
        for (const choice of choices) {
          let result
          try {
            result = await step(peer.request('session/set_config_option', { sessionId: acpSessionId, configId: profile.config.model, value: choice.value }))
          } catch (error) {
            // Agents can advertise a choice they then refuse (mcode 0.7.6 rejects its own non-thinking Flash variant);
            // leave it out so it cannot be selected, but a closed connection or timeout still fails the probe.
            if (error instanceof RpcRequestError && error.code !== -32000) {
              refusal = error
              continue
            }
            throw error
          }
          if (!configOption(result?.configOptions, profile.config.model)) throw new Error(`${profile.label} did not return the updated model configuration`)
          models.push(profile.modelOption ? profile.modelOption(choice, result?.configOptions, model.currentValue) : modelOption(choice, result?.configOptions, model.currentValue, profile.config.effort))
        }
        if (!models.length) throw new Error(`${profile.label} refused every advertised model: ${refusal?.message ?? 'no choices'}`)
        return models
      } finally {
        clearTimeout(timer)
        if (peer) await closeSession(peer, acpSessionId)
        if (child) {
          await stop({ child, exited })
          await Promise.race([exited, grace()])
          if (!probeExited) {
            child.kill('SIGKILL')
            await Promise.race([exited, grace()])
          }
          if (!probeExited) throw new Error(`${profile.label} model probe process failed to exit`)
          startingChildren.delete(child)
        }
        rmSync(prepared.cwd, { recursive: true, force: true })
        for (const file of prepared.files) rmSync(file.path, { force: true })
      }
    },

    async dispatchTurn(input) {
      if (disposed) throw new DispatchError('rejected', `${profile.label} runtime is closed`)
      if (runs.has(input.sessionId)) throw new DispatchError('rejected', 'This session already has an active turn')
      const prepared = prepare(input.sessionId, input.projectContext?.skillsPath, input.workContext)
      const { cwd, sandbox } = prepared
      const { token, tokenHash } = opts.issueToken()
      const instanceId = startTurnInstance(db, { sessionId: input.sessionId, turnId: input.turnId, tokenHash }, now())

      let child: ChildLike
      try {
        child = launch(prepared)
        if (sandbox.notice && opts.dataDir) report({ type: 'item', sessionId: input.sessionId, turnId: input.turnId, itemId: `sandbox:${input.turnId}`, revision: 1, kind: 'notice', payload: { code: 'sandbox_read_only', message: sandbox.notice } })
      } catch (error) {
        exit(instanceId, 'start_failed')
        throw new DispatchError('rejected', `Cannot start ${profile.label}: ${errorMessage(error)}`)
      }

      let rejectClosed!: (error: Error) => void
      const closed = new Promise<never>((_, reject) => { rejectClosed = reject })
      closed.catch(() => {})
      let resolveExited!: () => void
      let resolveDone!: () => void
      const run: Run = {
        sessionId: input.sessionId,
        turnId: input.turnId,
        instanceId,
        child,
        peer: undefined as unknown as Run['peer'],
        exited: new Promise<void>(r => { resolveExited = r }),
        acpSessionId: null,
        translate: null,
        toolCalls: new Map(),
        permissionsExpanded: !sandbox.notice,
        accepted: false,
        interrupted: false,
        ended: false,
        backlog: [],
        onFirstUpdate: undefined,
        pendingApprovals: 0,
        done: new Promise<void>(r => { resolveDone = r }),
        resolveDone: () => resolveDone(),
      }
      runs.set(input.sessionId, run)
      processes.add(run)
      child.once('error', error => rejectClosed(error))
      child.once('exit', () => {
        // Stay tracked until the turn is recorded; disposal must not outrun it.
        void run.done.then(() => processes.delete(run))
        resolveExited()
        rejectClosed(new Error(`${profile.processLabel} has exited`))
        // Process exit after acceptance: the turn did not finish normally, so treat it as interrupted (0004)
        if (run.accepted) void finish(run, 'interrupted').then(resolveDone)
        else resolveDone()
      })
      run.peer = createRpcPeer({ input: child.stdout, output: child.stdin }, {
        onNotification: (method, params) => { if (method === 'session/update') handleUpdate(run, params) },
        onRequest: (method, params) => {
          activity(run)
          return handleRequest(run, method, params)
        },
        onClose: () => rejectClosed(new Error(`${profile.processLabel} connection is closed`)),
      })

      const timeoutMs = opts.startTimeoutMs ?? 60_000
      let timer: ReturnType<typeof setTimeout> | undefined
      const timeout = new Promise<never>((_, reject) => { timer = setTimeout(() => reject(new StartTimeout()), timeoutMs) })
      const step = <T>(p: Promise<T>) => Promise.race([p, closed, timeout])
      let prompt: Promise<any>
      try {
        await step(run.peer.request('initialize', {
          protocolVersion: ACP_PROTOCOL_VERSION,
          clientCapabilities: { fs: { readTextFile: false, writeTextFile: false }, terminal: false },
          clientInfo: { name: 'vis-creative', version: '0.0.0' },
        }))
        const mcpServers = [{
          name: MCP_SERVER,
          command: opts.visMcp.command,
          args: opts.visMcp.args,
          env: [...Object.entries(nodeChildEnv(opts.visMcp.command)).map(([name, value]) => ({ name, value })), { name: 'VIS_SOCKET', value: opts.socketPath }, { name: 'VIS_AGENT_TOKEN', value: token }],
        }]
        let configOptions: unknown
        const createSession = async () => {
          const result = await step(run.peer.request('session/new', { cwd, mcpServers }))
          configOptions = result?.configOptions
          defaultModel = configOption(configOptions, profile.config.model)?.currentValue ?? defaultModel
          return String(result?.sessionId)
        }
        const config = input.agentConfig ?? { model: null, effort: null, serviceTier: null }
        if (input.resumeId && profile.config.model && config.model === null && defaultModel === undefined) {
          // Resumed values are not overlay defaults; obtain opaque values without guessing or decoding model IDs.
          // Finish the probe before resuming: another session lifecycle can disrupt the Agent's active session.
          const fresh = await step(run.peer.request('session/new', { cwd, mcpServers: [] }))
          try {
            defaultModel = configOption(fresh?.configOptions, profile.config.model)?.currentValue
          } finally {
            await closeSession(run.peer, fresh?.sessionId ?? null)
          }
        }
        if (input.resumeId) {
          try {
            const result = await step(run.peer.request(profile.resume, { sessionId: input.resumeId, cwd, mcpServers }))
            configOptions = result?.configOptions
            run.acpSessionId = input.resumeId
          } catch (error) {
            // An explicit RPC error on resume permits a new session: start a new one so retries do not keep getting stuck on the same invalid ID
            if (!(error instanceof RpcRequestError)) throw error
            run.acpSessionId = await createSession()
          }
        } else {
          run.acpSessionId = await createSession()
        }
        const permission = profile.config.permission
        if (permission && !configOption(configOptions, permission.id)) throw new Error(`${profile.label} did not provide permission configuration`)
        const currentModel = configOption(configOptions, profile.config.model)
        if (currentModel && config.model === null && defaultModel === undefined) throw new Error(`${profile.label} did not return a default model`)
        const model = config.model ?? defaultModel
        if (config.model !== null && !currentModel) throw new Error(`${profile.label} did not provide model configuration`)
        if (currentModel && model !== undefined && model !== currentModel.currentValue) {
          const result = await step(run.peer.request('session/set_config_option', { sessionId: run.acpSessionId, configId: profile.config.model, value: model }))
          configOptions = result?.configOptions
          if (!configOption(configOptions, profile.config.model)) throw new Error(`${profile.label} did not return the updated model configuration`)
        }
        const reasoning = configOption(configOptions, profile.config.effort)
        if (config.effort !== null && !reasoning) throw new Error(`The current ${profile.label} model does not support reasoning effort`)
        if (reasoning) {
          const effort = config.effort ?? profile.defaultEffort(reasoning)
          if (effort !== reasoning.currentValue) {
            const result = await step(run.peer.request('session/set_config_option', { sessionId: run.acpSessionId, configId: profile.config.effort, value: effort }))
            configOptions = result?.configOptions
            if (!configOption(configOptions, profile.config.effort)) throw new Error(`${profile.label} did not return the updated reasoning effort configuration`)
          }
        }
        if (permission) {
          const currentPermission = configOption(configOptions, permission.id)
          if (!currentPermission) throw new Error(`${profile.label} did not provide permission configuration`)
          if (currentPermission.currentValue !== permission.ask) {
            const result = await step(run.peer.request('session/set_config_option', { sessionId: run.acpSessionId, configId: permission.id, value: permission.ask }))
            if (configOption(result?.configOptions, permission.id)?.currentValue !== permission.ask) throw new Error(`${profile.label} did not confirm the asking permission mode`)
          }
        }
        run.translate = createTranslator(run.acpSessionId, run.turnId, profile.itemPrefix)
        if (disposed) throw new Error(`${profile.label} runtime is closed`)
        report({ type: 'resume_id', sessionId: input.sessionId, resumeId: run.acpSessionId })
        markInstanceReady(db, instanceId, child.pid)
        prompt = run.peer.request('session/prompt', { sessionId: run.acpSessionId, prompt: [
          ...(profile.instructions === 'prompt' ? [{ type: 'text', text: agentInstructions({ environment: { access: run.permissionsExpanded ? 'expanded' : 'readOnly', isolation: sandbox.isolation }, work: input.workContext }) }] : []),
          { type: 'text', text: turnPrompt(input) },
        ] })
        prompt.catch(() => {})
      } catch (error) {
        if (runs.get(input.sessionId) === run) runs.delete(input.sessionId)
        startingChildren.delete(child)
        await closeSession(run.peer, run.acpSessionId)
        await stop(run)
        if (error instanceof StartTimeout) {
          exit(instanceId, 'start_timeout')
          throw new DispatchError('rejected', `Waiting for ${profile.label} startup exceeded ${Math.round(timeoutMs / 1000)} seconds`)
        }
        exit(instanceId, 'start_failed')
        throw new DispatchError('rejected', `${profile.label} startup failed: ${errorMessage(error)}`)
      } finally {
        clearTimeout(timer)
      }

      // Acceptance: explicit rejection shortly after sending -> rejected; process exit -> unknown; an update, early completion, or interval expiry -> accepted
      let admissionTimer: ReturnType<typeof setTimeout> | undefined
      const admitted = new Promise<'admitted'>(r => {
        run.onFirstUpdate = () => r('admitted')
        admissionTimer = setTimeout(() => r('admitted'), opts.admissionMs ?? 1500)
      })
      let early: { result: any } | undefined
      try {
        const raced = await Promise.race([admitted, prompt.then(result => ({ result })), closed])
        if (disposed) throw new Error(`${profile.label} runtime is closed`)
        if (raced !== 'admitted') early = raced
      } catch (error) {
        if (runs.get(input.sessionId) === run) runs.delete(input.sessionId)
        await stop(run)
        if (error instanceof RpcRequestError && error.code !== -32000) {
          exit(instanceId, 'start_failed')
          throw new DispatchError('rejected', `${profile.label} rejected this message: ${errorMessage(error)}`)
        }
        exit(instanceId, 'start_failed')
        throw new DispatchError('unknown', `${profile.label} exited while processing the message: ${errorMessage(error)}`)
      } finally {
        startingChildren.delete(child)
        clearTimeout(admissionTimer)
        run.onFirstUpdate = undefined
      }

      if (run.ended) throw new DispatchError('rejected', 'Turn was terminated during startup')
      runs.set(input.sessionId, run)
      run.accepted = true
      activity(run)
      // The turn continues in the background; dispatchTurn only reports acceptance
      for (const update of run.backlog.splice(0)) handleUpdate(run, { sessionId: run.acpSessionId, update })
      const settle = early ? Promise.resolve(early.result) : prompt
      settle.then(
        result => finish(run, run.interrupted ? 'interrupted' : stopStatus(result?.stopReason)),
        error => {
          // A disconnected connection means the process exited mid-turn; treat it as interrupted (0004)
          if (error instanceof RpcRequestError && error.code === -32000) return finish(run, 'interrupted')
          if (!run.interrupted && !run.ended) {
            // Turn failure (for example, no configured API key): write the reason to the transcript
            report({ type: 'item', sessionId: run.sessionId, turnId: run.turnId, itemId: `${profile.itemPrefix}:${run.acpSessionId}:${run.turnId}:error`, revision: 1, kind: 'notice', payload: { code: 'agent_error', message: errorMessage(error) } })
          }
          return finish(run, run.interrupted ? 'interrupted' : 'failed')
        },
      ).then(resolveDone)
    },

    async interruptTurn({ sessionId, turnId }) {
      const run = runs.get(sessionId)
      if (!run || run.turnId !== turnId || run.ended) return
      run.interrupted = true
      clearTimeout(run.inactivityTimer)
      run.peer.notify('session/cancel', { sessionId: run.acpSessionId })
      // Stop the process if still running after the grace period, then finalize as interrupted after process exit
      void Promise.race([run.done, grace()]).then(() => {
        if (!run.ended) {
          void terminateTurn({ sessionId, turnId })
        }
      })
    },

    async dispose() {
      disposed = true
      for (const child of startingChildren) void killTree(child, 'SIGKILL')
      const all = [...processes]
      for (const run of all) {
        run.interrupted = true
        clearTimeout(run.inactivityTimer)
      }
      // Wait for the whole tree to be stopped: on Windows children (MCP servers, commands) would otherwise keep the workspace busy
      await Promise.all(all.map(run => killTree(run.child, 'SIGKILL')))
      await Promise.all(all.map(r => r.done))
    },
  }
}

class StartTimeout extends Error {}

function stopStatus(stopReason: unknown): TurnStatus {
  if (stopReason === 'end_turn') return 'completed'
  if (stopReason === 'cancelled') return 'interrupted'
  return 'failed'
}

function writeIfChanged(path: string, content: string) {
  let current: string | undefined
  try {
    current = readFileSync(path, 'utf8')
  } catch {
    // Not written yet
  }
  if (current !== content) writeFileSync(path, content)
}

function errorMessage(error: unknown): string {
  return error instanceof Error ? error.message : String(error)
}
