import { codexSandbox } from './descriptor'
import { mkdirSync, mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { delimiter, join } from 'node:path'
import { type AgentKind, AgentModelOption } from '@vis/protocol'
import type { SpaceDb } from '@vis/storage'
import { agentInstructions, type AgentEvent, type AgentRuntimePort, type AgentStreamEvent, type ApprovalRequest, type ChildLike, createRpcPeer, DispatchError, exitInstance, markInstanceReady, type RequestApproval, RpcRequestError, type SpawnFn, startTurnInstance } from '@vis/workbench-core'
import { buildPrompt } from './prompt'
import { translate } from './translate'
import { killTree, spawnAgentProcess, prepareSandbox, resolveExecutable } from '@vis/workbench-core'

/** macOS uses outer Seatbelt protection; Windows has no isolation; other cases without isolation remain read-only. */
export const SANDBOX = 'read-only'
export const APPROVAL_POLICY = 'on-request'
export const MCP_SERVER = 'vis'

export type CodexRuntimeOptions = {
  spawn?: SpawnFn
  codexPath?: string
  /** Directory containing the vis command generated by studiod, added to the Agent PATH */
  cliBinDir?: string
  /** Session working directory, also used as the Codex thread cwd */
  workDir(sessionId: string): string
  /** Issue a runtime token; store only its hash in the database */
  issueToken(): { token: string; tokenHash: string }
  socketPath: string
  /** studiod data root; remain read-only when absent */
  dataDir?: string
  forbiddenPaths?: readonly string[]
  /** Command to start the vis MCP server, such as node <cli>/vis.mjs mcp */
  visMcp: { command: string; args: string[] }
  model?: string
  /** Maximum wait from startup to the turn/start response */
  startTimeoutMs?: number
  /** Grace period for Codex cleanup after interruption; stop the process immediately on timeout */
  interruptGraceMs?: number
  env?: Record<string, string | undefined>
  now?: () => number
}

type TurnStatus = 'completed' | 'failed' | 'interrupted'

type Run = {
  sessionId: string
  turnId: string
  instanceId: string
  child: ChildLike
  peer: ReturnType<typeof createRpcPeer>
  threadId: string | null
  codexTurnId: string | null
  permissionsExpanded: boolean
  accepted: boolean
  interrupted: boolean
  ended: boolean
  planRevision: number
  fileChanges: Map<string, unknown>
  /** Notifications received before acceptance, processed in order after acceptance */
  backlog: { method: string; params: any }[]
  done: Promise<void>
  startup: Promise<void>
  /** Resolves when the app-server process has actually exited, which can lag behind `done` */
  exited: Promise<void>
  /** Set once the process tree has been told to stop */
  stopped?: Promise<void>
  finish(status: TurnStatus): void
}

/**
 * Start one codex app-server per turn: handshake, start or resume the thread, then start the turn; the process exits when the turn ends.
 * A turn/start response means acceptance; all subsequent endings are reported through turn_ended.
 */
export function createCodexRuntime(
  ctx: { db: SpaceDb; report: (event: AgentEvent) => void; stream?: (event: AgentStreamEvent) => void; requestApproval?: RequestApproval },
  opts: CodexRuntimeOptions,
): AgentRuntimePort & { agentOptions(agentKind: AgentKind, options: { model?: string }): Promise<AgentModelOption[]>; dispose(): Promise<void> } {
  const { db, report } = ctx
  const now = opts.now ?? Date.now
  const spawn = opts.spawn ?? spawnAgentProcess
  const runs = new Map<string, Run>()
  const processes = new Set<Run>()
  const startingChildren = new Map<ChildLike, Promise<void>>()
  let disposed = false

  const exit = (instanceId: string, reason: string) => exitInstance(db, instanceId, reason, now())

  function startServer(cwd: string) {
    const sandbox = prepareSandbox({ cwd, agent: opts.forbiddenPaths ? { ...codexSandbox, forbiddenPaths: opts.forbiddenPaths } : codexSandbox, ...(opts.dataDir ? { dataDir: opts.dataDir } : {}), ...(opts.env ? { env: opts.env } : {}) })
    if (opts.cliBinDir) sandbox.env.PATH = [opts.cliBinDir, sandbox.env.PATH].filter(Boolean).join(delimiter)
    const executable = resolveExecutable('codex', opts.codexPath, sandbox.env)
    const args = [...executable.args, 'app-server', '-c', 'model_reasoning_summary="auto"']
    const child = sandbox.policy
      ? spawn('/usr/bin/sandbox-exec', ['-p', sandbox.policy, executable.command, ...args], { cwd, env: sandbox.env })
      : spawn(executable.command, args, { cwd, env: sandbox.env })
    return { sandbox, child }
  }

  function handleNotification(run: Run, method: string, params: any) {
    if (method === 'item/started' && params?.item?.type === 'fileChange') run.fileChanges.set(params.item.id, params.item.changes)
    if (!run.accepted) {
      run.backlog.push({ method, params })
      return
    }
    if (run.ended) return
    switch (method) {
      case 'item/started':
      case 'item/completed': {
        const phase = method === 'item/started' ? 'started' : 'completed'
        for (const item of translate(phase, String(params?.turnId ?? run.codexTurnId), params?.item)) {
          report({ type: 'item', sessionId: run.sessionId, turnId: run.turnId, ...item })
        }
        break
      }
      case 'turn/plan/updated':
        if (Array.isArray(params?.plan)) {
          report({ type: 'item', sessionId: run.sessionId, turnId: run.turnId,
            itemId: `cx:${String(params.turnId ?? run.codexTurnId)}:plan`, revision: ++run.planRevision, kind: 'plan',
            payload: { entries: params.plan.map((entry: any) => ({ text: entry.step, status: entry.status === 'inProgress' ? 'in_progress' : entry.status })), ...(typeof params.explanation === 'string' ? { explanation: params.explanation } : {}) },
          })
        }
        break
      case 'item/reasoning/summaryPartAdded':
        if (params?.summaryIndex > 0) ctx.stream?.({ sessionId: run.sessionId, turnId: run.turnId, itemId: `cx:${String(params.turnId ?? run.codexTurnId)}:${params.itemId}`, revision: 2, kind: 'reasoning', delta: '\n\n' })
        break
      case 'item/reasoning/summaryTextDelta':
      case 'item/agentMessage/delta':
        // Match translate entry IDs: text persisted on completion replaces streaming fragments
        if (typeof params?.delta === 'string' && params.delta) {
          ctx.stream?.({ sessionId: run.sessionId, turnId: run.turnId, kind: method === 'item/agentMessage/delta' ? 'assistant_text' : 'reasoning', itemId: `cx:${String(params.turnId ?? run.codexTurnId)}:${params.itemId}`, revision: method === 'item/agentMessage/delta' ? 1 : 2, delta: params.delta })
        }
        break
      case 'thread/compacted':
        report({ type: 'context_compacted', sessionId: run.sessionId })
        break
      case 'error':
        if (!params?.willRetry) console.error(`[codex] ${run.sessionId} turn ${run.turnId} failed`, params?.error)
        break
      case 'turn/completed': {
        if (run.codexTurnId && params?.turn?.id !== run.codexTurnId) break
        const status = params?.turn?.status
        run.finish(run.interrupted || status === 'interrupted' ? 'interrupted' : status === 'completed' ? 'completed' : 'failed')
        break
      }
    }
  }

  async function handleRequest(run: Run, method: string, params: any): Promise<unknown> {
    const approve = async (kind: ApprovalRequest['kind'], summary: string, detail: string, evidence: Pick<ApprovalRequest, 'paths' | 'mcpTool' | 'autoApprovalBlocked'> = {}) => {
      if (!ctx.requestApproval || disposed || run.ended || run.interrupted) return 'deny'
      try {
        const cwd = params?.cwd === undefined ? opts.workDir(run.sessionId) : typeof params.cwd === 'string' ? params.cwd : undefined
        const decision = await ctx.requestApproval({ sessionId: run.sessionId, turnId: run.turnId, kind, summary, detail, ...(cwd === undefined ? {} : { cwd }), ...evidence })
        return disposed || run.ended || run.interrupted ? 'deny' : decision
      } catch {
        return 'deny'
      }
    }
    switch (method) {
      case 'item/commandExecution/requestApproval':
      case 'execCommandApproval': {
        const command = Array.isArray(params?.command) ? params.command.join(' ') : params?.command
        const additionalPermissions = params?.additionalPermissions ?? params?.additional_permissions
        const detail = [Array.isArray(params?.command) ? JSON.stringify(params.command) : command || `命令详情未提供：${params?.approvalId ?? params?.itemId ?? params?.callId ?? '未知'}`, params?.reason, params?.kind === 'writeStdin' ? `写入终端输入：${params?.itemId ?? '未知'}` : '', params?.networkApprovalContext ? JSON.stringify(params.networkApprovalContext) : '', additionalPermissions != null ? JSON.stringify(additionalPermissions) : '', params?.environmentId ? `环境：${params.environmentId}` : ''].filter(Boolean).join('\n')
        const autoApprovalBlocked = additionalPermissions != null || params?.environmentId != null || params?.kind === 'writeStdin'
        const decision = run.permissionsExpanded ? await approve(params?.networkApprovalContext ? 'network' : 'command', command || params?.reason || '执行命令', detail, { autoApprovalBlocked }) : 'deny'
        if (method === 'execCommandApproval') return { decision: decision === 'deny' ? { denied: { rejection: '用户未授权执行此命令' } } : 'approved' }
        return { decision: decision === 'deny' ? 'decline' : 'accept' }
      }
      case 'item/fileChange/requestApproval':
      case 'applyPatchApproval': {
        const changes = params?.fileChanges ?? run.fileChanges.get(params?.itemId)
        const hasChanges = changes && (Array.isArray(changes) ? changes.length : Object.keys(changes).length)
        const detail = [hasChanges ? JSON.stringify(changes, null, 2) : `文件变更详情未提供：${params?.itemId ?? params?.callId ?? '未知'}`, params?.grantRoot ? `写入根目录：${params.grantRoot}` : '', params?.reason].filter(Boolean).join('\n')
        let paths = fileChangePaths(changes)
        if (paths && params?.grantRoot != null) {
          if (typeof params.grantRoot === 'string') paths.push(params.grantRoot)
          else paths = undefined
        }
        const decision = run.permissionsExpanded ? await approve('file_write', params?.reason || `修改文件${params?.grantRoot ? `：${params.grantRoot}` : ''}`, detail, paths ? { paths } : {}) : 'deny'
        if (method === 'applyPatchApproval') return { decision: decision === 'deny' ? { denied: { rejection: '用户未授权修改文件' } } : 'approved' }
        return { decision: decision === 'deny' ? 'decline' : 'accept' }
      }
      case 'item/permissions/requestApproval': {
        const permissions = params?.permissions ?? {}
        const writes = permissions.fileSystem?.write?.length || permissions.fileSystem?.entries?.some((entry: any) => entry.access === 'write')
        const detail = [JSON.stringify(permissions, null, 2), params?.reason, params?.environmentId ? `环境：${params.environmentId}` : ''].filter(Boolean).join('\n')
        const decision = run.permissionsExpanded ? await approve(permissions.network?.enabled ? 'network' : writes ? 'file_write' : 'other', params?.reason || '扩展运行权限', detail) : 'deny'
        // The core matches session reuse exactly; do not enable the runtime's broader session permission cache.
        return { permissions: decision === 'deny' ? {} : permissions, scope: 'turn' }
      }
      case 'mcpServer/elicitation/request': {
        // Approvals only collect allow or deny decisions; they cannot fill required MCP forms for users.
        if (params?.requestedSchema?.required?.length) return { action: 'decline' }
        const detail = [`MCP：${params?.serverName ?? ''}`, params?.toolName ? `工具：${params.toolName}` : '', params?.message, params?.url, params?.requestedSchema ? JSON.stringify(params.requestedSchema, null, 2) : ''].filter(Boolean).join('\n')
        const confirmation = typeof params?.message === 'string' ? params.message.match(/^Allow the vis MCP server to run tool "([A-Za-z0-9_-]+)"\?$/) : undefined
        const toolName = typeof params?.toolName === 'string' ? params.toolName : confirmation?.[0] === params?.message ? confirmation?.[1] : undefined
        const emptyForm = params?.mode === 'form' && params?.requestedSchema && typeof params.requestedSchema === 'object' && !Array.isArray(params.requestedSchema) && !Object.keys(params.requestedSchema.properties ?? {}).length
        const mcpTool: ApprovalRequest['mcpTool'] = params?.serverName === MCP_SERVER && emptyForm && typeof toolName === 'string' && toolName.length > 0 && !/[^A-Za-z0-9_-]/.test(toolName) ? { serverName: MCP_SERVER, toolName } : undefined
        // Allow only recognized vis tool confirmations; the gateway still validates caller, workspace hierarchy, and turn
        if (mcpTool && !disposed && !run.ended && !run.interrupted) return { action: 'accept', content: {} }
        const decision = await approve(params?.mode === 'url' ? 'network' : 'other', params?.message || `MCP ${params?.serverName ?? ''} 请求授权`, detail, mcpTool ? { mcpTool } : {})
        return decision !== 'deny' ? { action: 'accept', content: {} } : { action: 'decline' }
      }
      default:
        throw new RpcRequestError(-32601, `Unsupported request: ${method}`)
    }
  }

  /**
   * turn/start model / effort overrides persist into later thread turns, so "default" cannot mean omission;
   * explicitly send the Agent defaults back, or restoring defaults still uses the previous overrides.
   * Speed uses serviceTierForTurn for this turn only, without changing thread settings; omission retains Codex's own configuration
   */
  async function turnOverrides(config: { model: string | null; effort: string | null; serviceTier: string | null } | undefined, request: (params: Record<string, unknown>) => Promise<any>): Promise<{ model?: string; effort?: string; serviceTierForTurn?: string }> {
    if (!config) return {}
    const tier = config.serviceTier ? { serviceTierForTurn: config.serviceTier } : {}
    let model = config.model
    let effort = config.effort
    if (model === null || effort === null) {
      const models = await listModels(request).catch(() => [])
      model ??= models.find(option => option.isDefault)?.id ?? null
      effort ??= models.find(option => option.id === model)?.defaultEffort ?? null
    }
    return { ...(model ? { model } : {}), ...(effort ? { effort } : {}), ...tier }
  }

  /** Speed tiers: newer versions provide serviceTiers, older ones only deprecated additionalSpeedTiers strings; treat malformed data as absent without affecting the model list */
  function serviceTiersOf(model: any): AgentModelOption['serviceTiers'] {
    if (Array.isArray(model?.serviceTiers) && model.serviceTiers.length) {
      return model.serviceTiers
        .filter((tier: any) => typeof tier?.id === 'string' && tier.id && tier.id !== 'default')
        .map((tier: any) => ({ id: tier.id, label: typeof tier.name === 'string' && tier.name ? tier.name : tier.id, ...(typeof tier.description === 'string' && tier.description ? { description: tier.description } : {}) }))
    }
    return Array.isArray(model?.additionalSpeedTiers)
      ? model.additionalSpeedTiers.filter((tier: unknown): tier is string => typeof tier === 'string' && tier !== '' && tier !== 'default').map((tier: string) => ({ id: tier, label: tier }))
      : []
  }

  /** Read the Codex model catalog (without calling a model); shared by probes and pre-turn default resolution */
  async function listModels(request: (params: Record<string, unknown>) => Promise<any>): Promise<AgentModelOption[]> {
    const models: AgentModelOption[] = []
    const cursors = new Set<string>()
    let cursor: string | undefined
    do {
      const page = await request({ includeHidden: false, ...(cursor ? { cursor } : {}) })
      if (!Array.isArray(page?.data) || (page.nextCursor != null && typeof page.nextCursor !== 'string')) throw new Error('Invalid Codex model catalog format')
      for (const model of page.data) {
        if (model?.hidden === true) continue
        if (model?.hidden !== false || !Array.isArray(model.supportedReasoningEfforts)) throw new Error('Invalid Codex model catalog format')
        models.push(AgentModelOption.parse({
          id: model.id, label: model.displayName, description: model.description,
          isDefault: opts.model ? model.id === opts.model || model.model === opts.model : model.isDefault,
          efforts: model.supportedReasoningEfforts.map((effort: any) => ({ id: effort?.reasoningEffort, label: effort?.reasoningEffort, description: effort?.description })),
          defaultEffort: model.defaultReasoningEffort,
          serviceTiers: serviceTiersOf(model),
        }))
      }
      cursor = page.nextCursor ?? undefined
      if (cursor && cursors.has(cursor)) throw new Error('Repeated Codex model catalog pagination cursor')
      if (cursor) cursors.add(cursor)
    } while (cursor)
    return models
  }

  async function terminateTurn({ sessionId, turnId }: { sessionId: string; turnId: string }) {
    const run = runs.get(sessionId)
    if (!run || run.turnId !== turnId) return
    run.interrupted = true
    const killed = killTree(run.child, 'SIGKILL')
    run.finish('interrupted')
    await killed
    await run.stopped
    await run.exited
  }

  return {
    terminateTurn,
    async agentOptions() {
      if (disposed) throw new Error('Codex runtime is closed')
      const cwd = mkdtempSync(join(tmpdir(), 'vis-codex-options-'))
      let child: ChildLike | undefined
      let exited: Promise<void> | undefined
      let timer: ReturnType<typeof setTimeout> | undefined
      try {
        child = startServer(cwd).child
        startingChildren.set(child, processExited(child))
        child.stderr?.resume()
        const probe = child
        exited = new Promise<void>(resolve => {
          probe.once('exit', resolve)
          probe.once('error', () => { if (probe.pid === undefined) resolve() })
        })
        let rejectClosed!: (error: Error) => void
        const closed = new Promise<never>((_, reject) => { rejectClosed = reject })
        child.once('error', error => rejectClosed(error))
        child.once('exit', () => rejectClosed(new Error('app-server has exited')))
        const peer = createRpcPeer({ input: child.stdout, output: child.stdin }, {
          onNotification: () => {},
          onRequest: method => { throw new RpcRequestError(-32601, `Unsupported request while probing the model catalog: ${method}`) },
          onClose: () => rejectClosed(new Error('app-server connection is closed')),
        })
        const timeout = new Promise<never>((_, reject) => { timer = setTimeout(() => reject(new Error('Timed out reading the Codex model catalog')), opts.startTimeoutMs ?? 60_000) })
        const step = <T>(p: Promise<T>) => Promise.race([p, closed, timeout])
        await step(peer.request('initialize', { clientInfo: { name: 'vis-creative', title: 'vis creative', version: '0.0.0' }, capabilities: null }))
        peer.notify('initialized')
        return await listModels(request => step(peer.request('model/list', request)))
      } finally {
        clearTimeout(timer)
        if (child) {
          void stop(child)
          const waitForExit = async () => {
            let timer: ReturnType<typeof setTimeout> | undefined
            try {
              return await Promise.race([exited!.then(() => true), new Promise<false>(resolve => { timer = setTimeout(() => resolve(false), opts.interruptGraceMs ?? 5000) })])
            } finally {
              clearTimeout(timer)
            }
          }
          if (!await waitForExit()) {
            child.kill('SIGKILL')
            if (!await waitForExit()) throw new Error('Cannot stop the Codex model catalog probe process')
          }
          startingChildren.delete(child)
        }
        rmSync(cwd, { recursive: true, force: true })
      }
    },

    async ensureReady(sessionId) {
      // One process per turn, with no persistent process to prepare; only ensure the working directory exists
      mkdirSync(opts.workDir(sessionId), { recursive: true })
    },

    async dispatchTurn(input) {
      if (disposed) throw new DispatchError('rejected', 'Codex runtime is closed')
      if (runs.has(input.sessionId)) throw new DispatchError('rejected', 'This session already has an active turn')
      const { token, tokenHash } = opts.issueToken()
      const instanceId = startTurnInstance(db, { sessionId: input.sessionId, turnId: input.turnId, tokenHash }, now())
      const cwd = opts.workDir(input.sessionId)

      let child: ChildLike
      let sandbox: ReturnType<typeof prepareSandbox>
      try {
        const server = startServer(cwd)
        sandbox = server.sandbox
        child = server.child
        startingChildren.set(child, processExited(child))
        if (sandbox.notice && opts.dataDir) report({ type: 'item', sessionId: input.sessionId, turnId: input.turnId, itemId: `sandbox:${input.turnId}`, revision: 1, kind: 'notice', payload: { code: 'sandbox_read_only', message: sandbox.notice } })
      } catch (error) {
        exit(instanceId, 'start_failed')
        throw new DispatchError('rejected', `Cannot start Codex: ${errorMessage(error)}`)
      }
      child.stderr?.resume()

      let resolveDone!: () => void
      let resolveStartup!: () => void
      let rejectClosed!: (error: Error) => void
      const closed = new Promise<never>((_, reject) => { rejectClosed = reject })
      closed.catch(() => {})
      const run: Run = {
        sessionId: input.sessionId,
        turnId: input.turnId,
        instanceId,
        child,
        peer: undefined as unknown as Run['peer'],
        threadId: null,
        codexTurnId: null,
        permissionsExpanded: !sandbox.notice,
        accepted: false,
        interrupted: false,
        ended: false,
        planRevision: 0,
        fileChanges: new Map(),
        backlog: [],
        done: new Promise<void>(r => { resolveDone = r }),
        startup: new Promise<void>(r => { resolveStartup = r }),
        exited: startingChildren.get(child)!,
        finish(status) {
          if (run.ended) return
          run.ended = true
          if (runs.get(run.sessionId) === run) runs.delete(run.sessionId)
          exit(instanceId, status)
          report({ type: 'turn_ended', sessionId: run.sessionId, turnId: run.turnId, status })
          run.stopped = stop(child, true)
          resolveDone()
        },
      }
      runs.set(input.sessionId, run)
      processes.add(run)
      void run.exited.then(async () => { await run.startup; await run.done; await run.stopped; processes.delete(run) })
      child.once('error', error => rejectClosed(error))
      child.once('exit', () => {
        rejectClosed(new Error('app-server has exited'))
        // Process exit after acceptance: the turn did not finish normally, so treat it as interrupted (0004)
        if (run.accepted) run.finish('interrupted')
        else resolveDone()
      })
      run.peer = createRpcPeer({ input: child.stdout, output: child.stdin }, {
        onNotification: (method, params) => handleNotification(run, method, params),
        onRequest: (method, params) => handleRequest(run, method, params),
        onClose: () => rejectClosed(new Error('app-server connection is closed')),
      })

      const timeoutMs = opts.startTimeoutMs ?? 60_000
      let timer: ReturnType<typeof setTimeout> | undefined
      const timeout = new Promise<never>((_, reject) => { timer = setTimeout(() => reject(new StartTimeout()), timeoutMs) })
      const step = <T>(p: Promise<T>) => Promise.race([p, closed, timeout])
      let turnSent = false
      let startupFailed = false
      try {
        await step(run.peer.request('initialize', { clientInfo: { name: 'vis-creative', title: 'vis creative', version: '0.0.0' }, capabilities: null }))
        run.peer.notify('initialized')
        if (input.projectContext) {
          try {
            await step(run.peer.request('skills/extraRoots/set', { extraRoots: [input.projectContext.skillsPath] }))
          } catch (error) {
            // Older versions without the extra-directory API can still read SKILL.md paths in this turn's directory.
            if (!(error instanceof RpcRequestError) || error.code !== -32601) throw error
          }
        }
        const instructions = agentInstructions({ environment: { access: sandbox.notice ? 'readOnly' : 'expanded', isolation: sandbox.isolation }, work: input.workContext })
        const threadParams = {
          cwd,
          sandbox: !sandbox.notice ? 'danger-full-access' : SANDBOX,
          approvalPolicy: APPROVAL_POLICY,
          developerInstructions: instructions,
          ...(opts.model ? { model: opts.model } : {}),
          config: {
            mcp_servers: {
              [MCP_SERVER]: { command: opts.visMcp.command, args: opts.visMcp.args, env: { VIS_SOCKET: opts.socketPath, VIS_AGENT_TOKEN: token } },
            },
            // Codex does not pass TMPPREFIX through to its shell; without it zsh here-documents hit the blocked /tmp.
            ...(sandbox.env.TMPPREFIX ? { shell_environment_policy: { set: { TMPPREFIX: sandbox.env.TMPPREFIX } } } : {}),
          },
        }
        let thread
        try {
          thread = await step(input.resumeId
            ? run.peer.request('thread/resume', { ...threadParams, threadId: input.resumeId })
            : run.peer.request('thread/start', threadParams))
        } catch (error) {
          // Codex explicitly errors on invalid threads (deleted or expired): start a new one so retries do not keep getting stuck on the same invalid ID
          if (!input.resumeId || !(error instanceof RpcRequestError)) throw error
          thread = await step(run.peer.request('thread/start', threadParams))
        }
        run.threadId = String(thread?.thread?.id ?? input.resumeId)
        report({ type: 'resume_id', sessionId: input.sessionId, resumeId: run.threadId })
        markInstanceReady(db, instanceId, child.pid)

        turnSent = true
        const started = await step(run.peer.request('turn/start', {
          threadId: run.threadId,
          input: [
            { type: 'text', text: buildPrompt(input), text_elements: [] },
            ...(input.projectContext?.skills.filter(skill => input.skills?.includes(skill.name)).map(skill => ({ type: 'skill', name: skill.name, path: skill.path })) ?? []),
          ],
          clientUserMessageId: input.turnId,
          ...await turnOverrides(input.agentConfig, request => step(run.peer.request('model/list', request))),
        }))
        if (disposed) throw new Error('Codex runtime is closed')
        run.codexTurnId = started?.turn?.id ?? null
      } catch (error) {
        startupFailed = true
        if (runs.get(input.sessionId) === run) runs.delete(input.sessionId)
        run.stopped = killTree(child, 'SIGKILL')
        if (error instanceof StartTimeout) {
          exit(instanceId, 'start_timeout')
          // A timeout before turn/start is sent proves Codex did not receive this message
          throw new DispatchError(turnSent ? 'unknown' : 'rejected', `Waiting for Codex startup exceeded ${Math.round(timeoutMs / 1000)} seconds`)
        }
        exit(instanceId, 'start_failed')
        // An explicit error response means the turn never started; a disconnected connection leaves it uncertain
        throw new DispatchError(turnSent && !(error instanceof RpcRequestError && error.code !== -32000) ? 'unknown' : 'rejected', `Codex startup failed: ${errorMessage(error)}`)
      } finally {
        clearTimeout(timer)
        startingChildren.delete(child)
        // Spawn errors need not emit exit; recording the failed startup settles its consumer too.
        if (startupFailed) resolveDone()
        resolveStartup()
      }

      if (run.ended) throw new DispatchError('rejected', 'Turn was terminated during startup')
      runs.set(input.sessionId, run)
      run.accepted = true
      // The turn continues in the background; dispatchTurn only reports acceptance
      for (const { method, params } of run.backlog.splice(0)) handleNotification(run, method, params)
    },

    async interruptTurn({ sessionId, turnId }) {
      const run = runs.get(sessionId)
      if (!run || run.turnId !== turnId) return
      run.interrupted = true
      const grace = new Promise<void>(r => setTimeout(r, opts.interruptGraceMs ?? 5000).unref())
      try {
        await Promise.race([run.peer.request('turn/interrupt', { threadId: run.threadId, turnId: run.codexTurnId }), grace])
      } catch {
        // If the interrupt request fails, stop the process directly
      }
      // Force-stop if still running after the grace period
      void Promise.race([run.done, grace]).then(() => { if (!run.ended) void terminateTurn({ sessionId, turnId }) })
    },

    async dispose() {
      disposed = true
      const pending = [...startingChildren]
      const all = [...processes]
      for (const run of all) {
        run.interrupted = true
        if (run.accepted) run.finish('interrupted')
      }
      await Promise.all([...new Set([...pending.map(([child]) => child), ...all.map(run => run.child)])].map(child => killTree(child, 'SIGKILL')))
      await Promise.all(pending.map(([, exited]) => exited))
      await Promise.all(all.map(r => r.startup))
      await Promise.all(all.map(r => r.done))
      await Promise.all(all.map(r => r.stopped))
      // A signal or completed taskkill is not evidence that Windows has released the cwd.
      await Promise.all(all.map(run => run.exited))
    },
  }
}

class StartTimeout extends Error {}

function fileChangePaths(changes: unknown): string[] | undefined {
  if (!changes || typeof changes !== 'object') return
  const entries = Array.isArray(changes) ? changes.map(change => [change?.path, change?.kind]) : Object.entries(changes)
  if (!entries.length) return
  const paths: string[] = []
  for (const [path, change] of entries) {
    if (typeof path !== 'string' || !change || !['add', 'delete', 'update'].includes(change.type)) return
    paths.push(path)
    for (const destination of [change.move_path, change.movePath]) {
      if (destination == null) continue
      if (typeof destination !== 'string') return
      paths.push(destination)
    }
  }
  return paths
}

function stop(child: ChildLike, force = false): Promise<void> {
  try { child.stdin.end() } catch { /* already exited */ }
  return killTree(child, force ? 'SIGKILL' : 'SIGTERM')
}

function errorMessage(error: unknown): string {
  return error instanceof Error ? error.message : String(error)
}


function processExited(child: ChildLike): Promise<void> {
  return new Promise(resolve => {
    child.once('exit', () => resolve())
    child.once('error', () => { if (child.pid === undefined) resolve() })
  })
}
