import { CloseIcon, IconButton, describeError, useFormat, useLocale, useMessages } from '@vis/ui-kit'
import { isBackdropClick } from './dialogBackdrop'
import { AgentChoices, usePreferredAgent, useAgents } from './agents'
import { dialogMessages } from './messages'
import type { AgentKind, SeriesView, SpaceSeries } from '@vis/protocol'
import { type KeyboardEvent, type SyntheticEvent, useEffect, useRef, useState } from 'react'
import { SeriesFields } from './SeriesProjectDialog'
import { nextEpisode, type ProjectSeriesInput, type SeriesProjectHost } from './series-model'
import { seriesProjectMessages } from './series-messages'

export type ProjectOption = { spaceId: string; name: string; rootPath: string; series?: SpaceSeries | undefined }
export type SkillOption = { name: string; description: string; path: string }
export type WorkspaceInput = { spaceId: string; title?: string; workDir?: string; agentKind: AgentKind }
export type DirectoryPicker = (defaultPath?: string) => Promise<string | undefined>

export function workspaceSlug(title: string): string {
  return title.trim().toLowerCase().replace(/[^\p{L}\p{N}._-]+/gu, '-').replace(/^[-.]+|[-.]+$/g, '')
}

export function useModal(onClose: () => void, hasUnsavedInput = false) {
  const dialog = useRef<HTMLDialogElement>(null)
  useEffect(() => {
    const previous = document.activeElement
    const element = dialog.current!
    element.showModal()
    element.querySelector<HTMLInputElement>('[data-initial-focus]')?.focus()
    return () => {
      element.close()
      if (previous instanceof HTMLElement && previous.isConnected) previous.focus()
    }
  }, [])
  return { ref: dialog, onClick: (event: React.MouseEvent<HTMLDialogElement>) => { if (!hasUnsavedInput && isBackdropClick(event)) onClose() }, onCancel: (event: SyntheticEvent) => { event.preventDefault(); onClose() } }
}

export function WorkspaceDialog(p: {
  projects: ProjectOption[]
  projectId: string
  onClose(): void
  onCreate(input: WorkspaceInput): Promise<void>
  onPickDirectory: DirectoryPicker
  onValidateDirectory(path: string): Promise<{ valid: boolean; error?: string }>
  onListSkills(input: { spaceId: string }): Promise<SkillOption[]>
}) {
  const agents = useAgents()
  const m = useMessages(dialogMessages)
  const format = useFormat()
  const { locale } = useLocale()
  const [spaceId, setSpaceId] = useState(p.projectId)
  const [title, setTitle] = useState('')
  const [createMore, setCreateMore] = useState(false)
  const [existing, setExisting] = useState(false)
  const [workDir, setWorkDir] = useState('')
  const [directoryError, setDirectoryError] = useState<{ message: 'directoryRequired' | 'directoryUnavailable' } | { error: unknown } | null>(null)
  const [agentKind, setAgentKind] = usePreferredAgent()
  const [skills, setSkills] = useState<SkillOption[]>([])
  const [skillError, setSkillError] = useState<unknown>(null)
  const [skillsLoading, setSkillsLoading] = useState(true)
  const [busy, setBusy] = useState(false)
  const validationRead = useRef(0)
  const nameInput = useRef<HTMLInputElement>(null)
  const initialAgent = useRef(agentKind)
  const modal = useModal(() => { if (!busy) p.onClose() }, Boolean(title || workDir || existing || createMore || spaceId !== p.projectId || agentKind !== initialAgent.current))
  const project = p.projects.find(project => project.spaceId === spaceId)
  const preview = `${project?.rootPath.replace(/\/$/, '') ?? ''}/workspaces/${workspaceSlug(title) || m.autoGeneratedDirectory}`
  useEffect(() => {
    let current = true
    setSkillsLoading(true)
    setSkillError(null)
    p.onListSkills({ spaceId }).then(list => { if (current) setSkills(list) }, error => {
      if (current) { setSkills([]); setSkillError(error) }
    }).finally(() => { if (current) setSkillsLoading(false) })
    return () => { current = false }
  }, [spaceId, p.onListSkills])
  const validateDirectory = async () => {
    const read = ++validationRead.current
    if (!workDir.trim()) { setDirectoryError({ message: 'directoryRequired' }); return false }
    try {
      const result = await p.onValidateDirectory(workDir.trim())
      if (read === validationRead.current) setDirectoryError(result.valid ? null : result.error ? { error: result.error } : { message: 'directoryUnavailable' })
      return result.valid
    } catch (error) {
      if (read === validationRead.current) setDirectoryError({ error })
      return false
    }
  }
  const create = async () => {
    if (busy || !agentKind || !project || !agents.some(agent => agent.kind === agentKind && agent.available)) return
    setBusy(true)
    setDirectoryError(null)
    try {
      if (existing && !await validateDirectory()) return
      await p.onCreate({ spaceId, agentKind, ...(title.trim() ? { title: title.trim() } : {}), ...(existing ? { workDir: workDir.trim() } : {}) })
      try { localStorage.setItem('vis.workspace.agent', agentKind) } catch { /* Ignore unavailable preference storage */ }
      if (createMore) { setTitle(''); nameInput.current?.focus() }
      else p.onClose()
    } catch (error) { setDirectoryError({ error }) }
    finally { setBusy(false) }
  }
  const onKeyDown = (event: KeyboardEvent) => {
    event.stopPropagation()
    if ((event.metaKey || event.ctrlKey) && event.key === 'Enter' && !event.nativeEvent.isComposing) { event.preventDefault(); void create() }
  }
  return <dialog {...modal} role="dialog" aria-modal="true" aria-label={m.newWorkspace} className="vis-dialog vis-workspace-dialog" onKeyDown={onKeyDown}>
    <form onSubmit={event => { event.preventDefault(); void create() }}>
      <div className="vis-dialog-header"><h2>{m.newWorkspace}</h2><IconButton type="button" label={m.close} disabled={busy} onClick={p.onClose}><CloseIcon /></IconButton></div>
      <div className="vis-dialog-body vis-workspace-fields"><label>{m.project}<div className="vis-dialog-project"><span aria-hidden="true">▧</span><select aria-label={m.project} value={spaceId} onChange={event => setSpaceId(event.target.value)}>{p.projects.map(project => <option key={project.spaceId} value={project.spaceId}>{project.name}</option>)}</select><span title={project?.rootPath}>{project?.rootPath}</span></div></label>
      <fieldset><legend>{m.workDirectory}</legend>
        <label className="vis-directory-radio"><input type="radio" name="directory" checked={!existing} onChange={() => { validationRead.current++; setExisting(false); setDirectoryError(null) }} />{m.createInProject}</label>
        {!existing ? <div className="vis-directory-preview" title={preview}>{preview}</div> : null}
        <label className="vis-directory-radio"><input type="radio" name="directory" checked={existing} onChange={() => setExisting(true)} />{m.useExistingDirectory}</label>
        {existing ? <div className="vis-directory-input"><input aria-label={m.existingDirectory} placeholder={m.directoryPlaceholder} value={workDir} onChange={event => { validationRead.current++; setWorkDir(event.target.value); setDirectoryError(null) }} onBlur={() => void validateDirectory()} /><button type="button" disabled={busy} onClick={() => void p.onPickDirectory(workDir || project?.rootPath).then(path => { if (path) { validationRead.current++; setWorkDir(path); setDirectoryError(null) } }, error => setDirectoryError({ error }))}>{m.pickDirectory}</button></div> : null}
        {directoryError ? <div className="vis-dialog-error" role="alert">{'message' in directoryError ? m[directoryError.message] : describeError(directoryError.error, locale)}</div> : null}
      </fieldset>
      <label>{m.optionalName}<input ref={nameInput} data-initial-focus aria-label={m.optionalWorkspaceName} placeholder={m.workspaceNamePlaceholder} maxLength={60} value={title} onChange={event => setTitle(event.target.value)} /></label>
      <fieldset><legend>{m.agent}</legend><div className="vis-agent-segment"><AgentChoices value={agentKind} onChange={setAgentKind} /></div></fieldset>
      <fieldset><legend>{m.optionalSkills}</legend><details className="vis-dialog-skills"><summary>{skillsLoading ? m.loadingSkills : m.skillCount(format.number(skills.length))}</summary>{skillError ? <div role="alert" className="vis-dialog-error">{describeError(skillError, locale)}</div> : skills.length ? skills.map(skill => <div className="vis-dialog-skill" key={skill.path}><strong>{skill.name}</strong><span>{skill.description}</span></div>) : <p>{m.noInstalledSkills}</p>}</details></fieldset>
      </div><div className="vis-dialog-footer vis-dialog-actions"><label className="vis-create-more"><input type="checkbox" checked={createMore} disabled={busy} onChange={event => setCreateMore(event.target.checked)} />{m.createMore}</label><button className="is-primary" type="submit" disabled={busy || !project || !agents.some(agent => agent.kind === agentKind && agent.available)}>{busy ? m.creating : m.createWorkspace}<kbd aria-hidden="true">⌘↵</kbd></button></div>
    </form>
  </dialog>
}

export function ProjectDialog(p: { projectsDir: string; seriesHost?: SeriesProjectHost | undefined; onClose(): void; onCreate(name: string, rootPath: string | undefined, agentKind: AgentKind | null, series?: ProjectSeriesInput): Promise<void>; onPickDirectory: DirectoryPicker }) {
  const agents = useAgents()
  const m = useMessages(dialogMessages)
  const seriesCopy = useMessages(seriesProjectMessages)
  const { locale } = useLocale()
  const [name, setName] = useState('')
  const [isEpisode, setIsEpisode] = useState(false)
  const [seriesItems, setSeriesItems] = useState<SeriesView[]>([])
  const [seriesId, setSeriesId] = useState('')
  const [seriesName, setSeriesName] = useState('')
  const [episode, setEpisode] = useState(1)
  // Open the first workspace when creating a project; null means only an empty canvas is wanted
  const [agentKind, setAgentKind] = usePreferredAgent()
  const [rootPath, setRootPath] = useState('')
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState<unknown>(null)
  const initialAgent = useRef(agentKind)
  const modal = useModal(() => { if (!busy) p.onClose() }, Boolean(name || rootPath || isEpisode || agentKind !== initialAgent.current))
  useEffect(() => {
    let active = true
    void p.seriesHost?.list().then(items => { if (active) setSeriesItems(items) }, cause => { if (active) setError(cause) })
    return () => { active = false }
  }, [p.seriesHost])
  const defaultPath = `${p.projectsDir.replace(/\/$/, '')}/${name.trim().replace(/[\\/]/g, '-').replace(/^\.{1,2}$/, '-') || m.projectNameDirectory}`
  const create = async () => {
    if (busy || !name.trim() || (agentKind !== null && !agents.some(agent => agent.kind === agentKind && agent.available))) return
    setBusy(true)
    setError(null)
    try { await p.onCreate(name.trim(), rootPath.trim() || undefined, agentKind, isEpisode ? { series: seriesId ? { seriesId } : { name: seriesName.trim() }, episode } : undefined); if (agentKind) { try { localStorage.setItem('vis.workspace.agent', agentKind) } catch { /* Ignore unavailable preference storage */ } } p.onClose() }
    catch (error) { setError(error) }
    finally { setBusy(false) }
  }
  return <dialog {...modal} role="dialog" aria-modal="true" aria-label={m.newProject} className="vis-dialog vis-workspace-dialog" onKeyDown={event => {
    event.stopPropagation()
    if ((event.metaKey || event.ctrlKey) && event.key === 'Enter') { event.preventDefault(); void create() }
  }}><form onSubmit={event => { event.preventDefault(); void create() }}>
    <div className="vis-dialog-header"><h2>{m.newProject}</h2><IconButton type="button" label={m.close} disabled={busy} onClick={p.onClose}><CloseIcon /></IconButton></div>
    <div className="vis-dialog-body vis-workspace-fields"><label>{m.projectName}<input data-initial-focus aria-label={m.projectName} maxLength={100} required value={name} onChange={event => setName(event.target.value)} /></label>
    {p.seriesHost ? <><fieldset disabled={busy}>
      <label className="vis-directory-radio"><input type="radio" name="project-series" checked={!isEpisode} onChange={() => setIsEpisode(false)} />{seriesCopy.standalone}</label>
      <label className="vis-directory-radio"><input type="radio" name="project-series" checked={isEpisode} onChange={() => setIsEpisode(true)} />{seriesCopy.newEpisode}</label>
    </fieldset>{isEpisode ? <SeriesFields items={seriesItems} selected={seriesId} name={seriesName} episode={episode}
      onSelect={id => { setSeriesId(id); setEpisode(nextEpisode(seriesItems.find(item => item.seriesId === id))) }} onName={setSeriesName} onEpisode={setEpisode} disabled={busy} /> : null}</> : null}
    <label>{m.location}<div className="vis-directory-input"><input aria-label={m.projectLocation} value={rootPath || defaultPath} onChange={event => setRootPath(event.target.value)} /><button type="button" disabled={busy} onClick={() => void p.onPickDirectory(rootPath || p.projectsDir || undefined).then(path => { if (path) setRootPath(path) }, error => setError(error))}>{m.pickDirectory}</button></div></label>
    <fieldset><legend>{m.firstWorkspaceAgent}</legend><div className="vis-agent-segment"><AgentChoices value={agentKind} onChange={setAgentKind} /><button type="button" aria-pressed={agentKind === null} onClick={() => setAgentKind(null)}>{m.doNotCreateYet}</button></div></fieldset>
    {error ? <div role="alert" className="vis-dialog-error">{describeError(error, locale)}</div> : null}
    </div><div className="vis-dialog-footer vis-dialog-actions"><button type="button" disabled={busy} onClick={p.onClose}>{m.cancel}</button><button className="is-primary" type="submit" disabled={busy || !name.trim() || (isEpisode && !seriesId && !seriesName.trim()) || (agentKind !== null && !agents.some(agent => agent.kind === agentKind && agent.available))}>{busy ? m.creating : m.createProject}</button></div>
  </form></dialog>
}
